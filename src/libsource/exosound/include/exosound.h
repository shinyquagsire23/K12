#pragma once
#include "k2stdint.h"

// The base-lib sound engine, a pimpl shell over CExoSoundInternal. Most methods are guarded
// forwarders or guarded field accessors that answer a fixed default on the null path.

#include "Vector.h"
#include "exoresman.h"

class CExoSoundInternal;

class CExoSound {
public:
    // Exported object symbols; defined out of line, deliberately without an in-class initialiser.
    static const unsigned char CMAX_VOLUME;
    static const int CEXOSOUND_MODE_GENERIC;
    static const int CEXOSOUND_MODE_MUTE;
    static const int CEXOSOUND_MODE_PAUSE;
    static const int CEXOSOUND_MODE_PAUSE_ALL;
    static const int CEXOSOUND_MODE_PAUSE_ALL_BUT_MUSIC;
    static const int CEXOSOUND_MODE_LOSTFOCUS;
    static const int CEXOSOUND_MODE_GAINFOCUS;

    CExoSound(unsigned char n2DVoices, unsigned char n3DVoices, int a, int b);
    ~CExoSound();

    void StartDuckingMusicAndAmbientSounds();
    void StopDuckingMusicAndAmbientSounds();

    void  SetMusicVolume(float fVolume, int nChannel);
    void  SetSoundEffectVolume(float fVolume);
    void  SetDialogVolume(float fVolume);
    float GetMusicVolume();
    float GetSoundEffectVolume();
    float GetDialogVolume();

    void  Set2D3DBias(float fBias);
    float Get2D3DBias();
    int   Test2D3DBias();

    void SetRollOffFactor(float f);
    int  GetNumber2DVoices();
    int  GetNumber3DVoices();
    void Render();

    void SetListenerOrientation(const Vector& vDir, const Vector& vUp);
    void SetListenerPosition(const Vector& vPos);
    void GetListenerPosition(Vector* pOut);

    void ReInitialize(int a, int b);

    int PlayOneShotSound(const CResRef& r, unsigned char a, unsigned int b, unsigned char c,
                         float d, float e);
    // The leading float is a Z offset added to the position before the hand-off. The result is the
    // sound's length in milliseconds.
    int Play3DOneShotSound(const CResRef& r, Vector vPos, float fZOffset, unsigned char a,
                           unsigned int b, unsigned char c, float d, float e);
    void StopAllOneShots();
    int  GetSpeakerType();
    void SetEnvironment(unsigned char env);

    void EnableStreamingEnvironmentEffects(int b);
    void EnableNonStreamingEnvironmentEffects(int b);
    int  GetStreamingEnvironmentEffectsEnabled();
    int  GetNonStreamingEnvironmentEffectsEnabled();

    void EnableHardwareSound(int b);
    int  GetHardwareSoundEnabled();
    void SetEAX(int n);
    int  GetEAX();
    int  GetBestEAXAvailable();

    void  SetEnvironmentEffectLevel(float f);
    float GetEnvironmentEffectLevel();

    int  RemoveAllSounds();
    void ResumeAllStreamingMusicForMovie();

    int  GetDisplayOcclusionInfo();
    void SetDisplayOcclusionInfo(int b);
    void SetDesiredEnvironment(int n);
    void SetDesiredAmbientScale(float f);

#if KOTOR1
    void SetSoundMode(int mode);
    void SetSoundMode(int mode, int) { SetSoundMode(mode); }
#else
    void SetSoundMode(int mode, int flag);
#endif
    int  GetSoundMode();

    void GetPriorityGroupDistance(int nGroup, float* pA, float* pDist);
    int  GetLostFocusPaused();

    CExoSoundInternal* m_pInternal;
};

// One playable non-streaming sound instance, a polymorphic pimpl shell over
// CExoSoundSourceInternal, whose only virtual is the destructor.

#include "exoresman.h"

class CExoSoundSourceInternal;

class CExoSoundSource {
public:
    CExoSoundSourceInternal* m_pInternal;

    CExoSoundSource();
    CExoSoundSource(const CResRef& resRef);

    int  CancelRequest();
    void SetPriorityGroup(unsigned char nGroup);
    int  Get3D();
    void Set3D(int b3D);
    // Exported name; do not rename.
    int  IsHardwarePlayingSoundPleaseDontUseThis();
    // Returns the sound's length in milliseconds.
    int  Play();
    int  Request();
    void SetVolume(unsigned char nVolume);
    void SetPitchVariance(float fVariance);
    float GetPitchVariance();
    void SetLooping(int bLooping);
    int  GetLooping();
    void SetPosition(const Vector& vPosition, float fZOffset);
    Vector GetPosition();
    void SetDistance(float fMinDistance, float fMaxDistance);
    void GetDistance(float* pfMinDistance, float* pfMaxDistance);
    void SetResRef(const CResRef& resRef, int bRequest);
    void Stop();
    void SetFixedVariance(float fVariance);
    float GetFixedVariance();

    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 2 slots
    virtual ~CExoSoundSource();
    // </VTABLE-GEN>
};

// A streaming sound instance (music, ambient, dialog, a soundset one-shot). The plainest shell in
// the sound library: a single internal pointer and no vtable.

#include "exoresman.h"

class CExoStreamingSoundSourceInternal;

class CExoStreamingSoundSource {
public:
    CExoStreamingSoundSourceInternal* m_pInternal;

#if KOTOR1
    // K1's signatures carry no stream type and no fade argument, so the shared call sites go
    // through these forwarders.
    CExoStreamingSoundSource();
    CExoStreamingSoundSource(int nType) : CExoStreamingSoundSource() { K2_UNUSED(nType); }
#else
    CExoStreamingSoundSource(int nType);
#endif
    ~CExoStreamingSoundSource();

    int  IsPlaying();
    int  IsDone();
    int  GetPlayFailed();
    // Non-zero when the stream started.
    int  Play(const CResRef& resRef, unsigned short a, int b, int c, int d);
    void Pause();
    void Resume();
    CResRef GetFilePlaying();
    void SetLooping(int bLooping);
    int  GetLooping();
    void SetVolume(unsigned char nVolume);
    unsigned char GetVolume();
#if KOTOR1
    void Stop();
    void Stop(int bFade) { K2_UNUSED(bFade); Stop(); }
#else
    void Stop(int bFade);
#endif
    void FadeAndStop(unsigned int nMilliseconds);
    void SetPriorityGroup(unsigned char nGroup);
    unsigned char GetPriorityGroup();
    void Set3D(int b3D);
    int  Get3D();
    void SetDistance(float fMinDistance, float fMaxDistance);
    void SetPosition(const Vector& vPosition);
    void SetReverbEnabled(int bEnabled);
    int  GetHasStartedStreaming();
    void SetStreamingMusicForMovie(int bForMovie);
    int  IsStreamingMusicForMovie();
};
