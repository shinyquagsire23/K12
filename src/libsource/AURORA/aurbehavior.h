class CAurObject;
class CAurPart;
class CallBack;

// The ids GetType reports for the behaviors below.
enum {
    kBehaviorAttach = 1001,
    kBehaviorAttachTranslate = 1002,
    kBehaviorAttachRotate = 1003,
    kBehaviorNavigate = 1004,
    kBehaviorCameraFollow = 1005,
    kBehaviorCameraLooseFollow = 1006,
    kBehaviorCameraOnAStick = 1007,
    kBehaviorAttachNoOrientation = 1008,
};

// Attaches the owner to another object, optionally to one of its parts, and keeps one callback
// registration per attached part so they can be deregistered together.
class CAurBehaviorAttach : public CAurBehavior {
public:

    virtual ~CAurBehaviorAttach();
    virtual void SetScene();
    virtual int Control(float fParam);
    virtual void Message(char* pszParam);
    virtual int GetType();
    virtual void* AsBehaviorAttach();
    virtual void UpdateGobPosition();

    SafePointer<CAurObject> m_pAttachedTo;
    CAurPart*               m_pAttachedPart;
    int  m_nReserved1;
    int  m_nDieWithoutParent;
    CallBack* m_pUpdateScenesCallBack;
    CallBack* m_pUpdatePositionCallBack;
    CallBack* m_pColorShiftCallBack;
    CallBack* m_pIlluminationCallBack;
    CallBack* m_pRenderCallBack;
    CallBack* m_pViewVolumeCallBack;

    CAurBehaviorAttach(CAurObject* pObject, CAurObject* pAttachTo, CAurPart* pPart);
};

inline int CAurBehaviorAttach::GetType() { return kBehaviorAttach; }
inline void* CAurBehaviorAttach::AsBehaviorAttach() { return this; }

#endif // CAURBEHAVIORATTACH_H

