// A packed surface normal: biased signed components plus a weight.
struct Normal {
    unsigned char m_bX;
    unsigned char m_bY;
    unsigned char m_bZ;
    unsigned char m_bW;
};

// Height field to normal map, one output texel per input sample.
Normal* convertHeightFieldToNormalMap(unsigned char* pData, int nWidth, int nHeight, int nStride,
                                      int nSrcHeight, float fScale);
// Halves a normal map, one texel per 2x2 source block.
Normal* downSampleNormalMap(Normal* pData, int nWidth, int nHeight, int nNewWidth,
                            int nNewHeight);

