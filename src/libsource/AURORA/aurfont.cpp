// Point the console at a named font, creating the shared StringGob on first use.
void SetConsoleFont(char* pszFont)
{
    if (!initialized)
        AurInitFont();

#if KOTOR1
    s_bUseBitmapFont = false;
#endif
    if (textureFont == 0)
        textureFont = new StringGob(1);

    consoleFont = textureFont->SetFont(pszFont);
#if KOTOR1
    if (consoleFont >= CAurFont::s_LoadedFontList.m_count)
        s_bUseBitmapFont = true;
#endif
}

#if !KOTOR1
// Compiles one display list per printable ASCII glyph out of the raster table.
inline void GLRender::SetUpTextFormat()
{
    ASLgl::glPixelStorei(GL_UNPACK_ALIGNMENT, 1);
    fontOffset = ASLgl::glGenLists(128);

    for (int i = 0; i < 95; i++) {
        ASLgl::glNewList(i + 32 + fontOffset, GL_COMPILE);
        ASLgl::glBitmap(8, 13, 0.0f, 2.0f, 10.0f, 0.0f, rasters[i]);
        ASLgl::glEndList();
    }
}
#endif

inline void GLRender::FreeTextFont()
{
    ASLgl::glDeleteLists(fontOffset, 128);
}

// Draw one line with the bitmap font in a 0..1 screen-space ortho projection.
inline void GLRender::PrintStringAtScreenPos(char* pszText, float fX, float fY)
{
    ASLgl::glPushAttrib(GL_TEXTURE_BIT | GL_DEPTH_BUFFER_BIT | GL_LIGHTING_BIT);
    ASLgl::glDisable(GL_TEXTURE_2D);
    ASLgl::glDisable(GL_LIGHTING);
    ASLgl::glDisable(GL_DEPTH_TEST);
    ASLgl::glMatrixMode(GL_PROJECTION);
    ASLgl::glPushMatrix();
    ASLgl::glLoadIdentity();
    ASLgl::glOrtho(0.0, 1.0, 0.0, 1.0, -1.0, 1.0);
    ASLgl::glRasterPos2f(fX, fY);
    SpitLetters(pszText);
    ASLgl::glRasterPos2f(0.0f, 0.0f);
    ASLgl::glPopMatrix();
    ASLgl::glMatrixMode(GL_MODELVIEW);
    ASLgl::glPopAttrib();
}

void AurInitFont()
{
#if KOTOR1  // K1: the console font is the texture font "fnt_console"; no bitmap display lists
    s_bUseBitmapFont = false;
    textureFont = new StringGob(1);
    consoleFont = textureFont->SetFont(const_cast<char*>("fnt_console"));
#else
    GLRender::SetUpTextFormat();
#endif
    initialized = 1;
}

void AurFreeFont()
{
    if (initialized) {
        initialized = 0;
        GLRender::FreeTextFont();
        delete textureFont;
        textureFont = 0;
    }
}

void PrintStringScreenPos(char* pszText, float fX, float fY)
{
    if (pszText == 0 || *pszText == 0)
        return;
    GLRender::PrintStringAtScreenPos(pszText, fX, fY);
}

// Draws the same line with the current texture font, in a centred hundredth-of-a-pixel ortho box.
// The two GL state changes at the top happen even for an empty string.
void PrintStringScreenPos_UseTextureFont(char* pszText, float fX, float fY)
{
    GLRender::Enable(Aurora::kCapBlend);
    GLRender::SetBlendFunc(Aurora::kBlendSrcAlpha, Aurora::kBlendInvSrcAlpha);

    if (pszText == 0 || *pszText == 0)
        return;

    int viewport[4];
    GLRender::GetViewPort(viewport);

    ASLgl::glPushAttrib(GL_ENABLE_BIT | GL_DEPTH_BUFFER_BIT | GL_LIGHTING_BIT);
    GLRender::Disable(Aurora::kCapDepthTest);
    GLRender::EnableColorMaterial();
    GLRender::SetMatrixMode(Aurora::kMatrixProjection);
    ASLgl::glPushMatrix();
    ASLgl::glLoadIdentity();

    ASLgl::glOrtho(static_cast<float>(-(viewport[2] / 2)) * 0.01f, (static_cast<float>(viewport[2] / 2)) * 0.01f,
                   static_cast<float>(-(viewport[3] / 2)) * 0.01f, (static_cast<float>(viewport[3] / 2)) * 0.01f, 0.0, 10.0);
    ASLgl::glTranslatef(fX * 0.01f, fY * 0.01f, 0.0f);

    CAurFont::s_LoadedFontList.m_pData[consoleFont]->m_pTexture.m_pObject->Bind();
    CAurFont::s_LoadedFontList.m_pData[consoleFont]->TextOutA(pszText, static_cast<int>(strlen(pszText)));

    ASLgl::glPopMatrix();
    GLRender::SetMatrixMode(Aurora::kMatrixModelView2);
    GLRender::Enable(Aurora::kCapDepthTest);
    GLRender::DisableColorMaterial();
    GLRender::Disable(Aurora::kCapBlend);
    ASLgl::glPopAttrib();
}

// A stub in the shipped K2 build. K1 has a real body: the grid is 7 by 10 pixels of the viewport, a
// negative column is right-aligned, and the font is the texture font unless SetConsoleFont fell
// back to the bitmap.
void AurPrintString(char* pszText, int nX, int nY)
{
#if !KOTOR1
    K2_UNUSED(pszText); K2_UNUSED(nX); K2_UNUSED(nY);
#endif
#if KOTOR1
    if (!g_bEnableAurPostString)
        return;

    int viewport[4];
    GLRender::GetViewPort(viewport);
    if (viewport[2] < 300 || viewport[3] < 100)
        return;

    int nCols = viewport[2] / 10;
    int nRows = viewport[3] / 2 / 7;
    if (nY >= nRows)
        nY = nRows - 1;
    if (nX < 0)
        nX = static_cast<int>(nX + nCols - strlen(pszText) + 1);
    if (nX + static_cast<int>(strlen(pszText)) > nCols)
        nX = static_cast<int>(nCols - strlen(pszText));

    GLRender::Disable(Aurora::kCapLighting);
    if (!initialized)
        AurInitFont();

    if (nY < 0)
        nY += nRows;
    if (nY < 0)
        nY = 0;
    if (nX < 0)
        nX = 0;
    float fX = static_cast<float>(nX) / static_cast<float>(nCols);
    nY = nRows - 1 - nY;
    if (!s_bUseBitmapFont)
        PrintStringScreenPos_UseTextureFont(pszText, fX * static_cast<float>(viewport[2]) - static_cast<float>(viewport[2] / 2),
                                            static_cast<float>(nY) / static_cast<float>(nRows) * static_cast<float>(viewport[3]) - static_cast<float>(viewport[3] / 2));
    else
        PrintStringScreenPos(pszText, fX, static_cast<float>(nY) / static_cast<float>(nRows));
    GLRender::Enable(Aurora::kCapLighting);
#endif
}

// Parses "r g b a r2 g2 b2 a2"; the second quad is the colour a timed message fades to. Fewer than
// five parsed fields means only one colour was given, so both ends get it.
