#ifndef CRESTXB_H
#define CRESTXB_H

// The BioWare texture (.txb) resource wrapper parses the TPC header, walks the mipmap chain to
// total the pixel-data size, and publishes views of the pixel data, the header and the trailing TXI
// block.
//
// The field and header layout matches CResTPC's, but the uncompressed path additionally rounds the
// totalled size up to a header-sized boundary and multiplies by the face count before storing
// m_nUncompressedSize, then falls into the shared tail; the compressed path matches CResTPC's walk.

#include "exoresman.h"

// The TPC file header parsed at the front of the header region.
struct TXBHeader {
    unsigned int  m_nDataSize;   // nonzero means compressed; the raw pixel byte count
    float         m_fAlphaTest;
    unsigned short m_width;
    unsigned short m_height;
    unsigned char m_formatBits;  // bits 0 to 2 select the pixel format
    unsigned char m_nMipCount;
    // Fixed-size header; pixel data starts right after it. The tail beyond the mip count is not
    // modelled.
    unsigned char _raw0e[0x72];
};

class CResTXB : public CRes {
public:
    CResTXB();
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 6 slots
    virtual ~CResTXB();  // slots 0-1 (D2+D0)
    virtual int OnResourceFreed();
    virtual int OnResourceServiced();
    // </VTABLE-GEN>

    int   GetTXBAttrib(int* pWidth, int* pHeight, char* pFormat, int* pnCompressedSize, int* pnUncompressedSize,
                       int* pTXISize, float* pAlphaTest, char* pMipCount);
    void* GetTXBDataPtr();
    void* GetTXBHeaderPtr();
    void* GetTXBTXIPtr();
    int   GetTXBSize();      // the compressed size when compressed, else the uncompressed one
    int   GetTXBTXISize();
    int   IsCompressed();
    int   IsLoaded();

    int          m_bCompressed;
    int          m_bLoaded;
    int          m_nUncompressedSize;      // uncompressed pixel size
    int          m_nCompressedSize;      // compressed pixel size
    int          m_nTXISize;
    void*        m_pTXBData;
    void*        m_pTXBHeader;   // the base buffer, as a TXBHeader*
    void*        m_pTXBTXI;      // the trailing TXI block
};

#endif
