#ifndef CRESBMP_H
#define CRESBMP_H

#include "exoresman.h"

// A Windows bitmap (.bmp) resource wrapper: parses the file and info headers at the front of the raw
// file buffer and publishes views of the info header, colour table and pixel data.

// The SDK's palette entry. GetPixelColor copies one whole entry at a time, so it must stay exactly
// 4 bytes wide.
struct tagRGBQUAD {
    unsigned char m_rgbBlue;
    unsigned char m_rgbGreen;
    unsigned char m_rgbRed;
    unsigned char m_rgbReserved;
};

// The Windows file header at the start of the file buffer, where m_pFileHeader points. Packed to 2
// bytes as the Windows SDK declares it; without the pragma every field after m_bfType is read two
// bytes late.
#pragma pack(push, 2)
struct BitmapFileHeader {
    unsigned short m_bfType;       // the 'BM' file magic
    unsigned int   m_bfSize;
    unsigned short m_bfReserved1;
    unsigned short m_bfReserved2;
    unsigned int   m_bfOffBits;    // pixel data offset
};
#pragma pack(pop)

// The parsed Windows info header, immediately after the file header. Only the fields the accessors
// touch are named.
struct BitmapInfoHeader {
    unsigned int   m_biSize;
    int            m_biWidth;
    int            m_biHeight;
    unsigned short m_biPlanes;
    unsigned short m_biBitCount;
    unsigned int   m_biCompression;   // must be BI_RGB (0)
    unsigned int   m_biSizeImage;
    int            m_biXPelsPerMeter;
    int            m_biYPelsPerMeter;
    unsigned int   m_biClrUsed;
    unsigned int   m_biClrImportant;
};

class CResBmp : public CRes {
public:
    CResBmp();
    CResBmp(unsigned int);
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 6 slots
    virtual ~CResBmp();  // slots 0-1 (D2+D0)
    virtual int OnResourceFreed();
    virtual int OnResourceServiced();
    // </VTABLE-GEN>

    int   GetBitDepth();
    int   GetColorCount();
    void* GetColorTable();
    void* GetImageData();
    void  GetImageDimensions(int& rWidth, int& rHeight);
    int   GetPixelColor(int x, int y, tagRGBQUAD& rQuad);
    int   GetPixelValue(int x, int y);
    int   IsLoaded();

    int   m_nColorCount;         // biClrUsed for 4/8-bit images, -1 for 24-bit
    int   m_nStride;       // row stride in DWORDs, not bytes
    void* m_pImageData;
    void* m_pFileHeader;   // also the start of the file buffer
    void* m_pInfoHeader;
    void* m_pColorTable;
    int   m_bLoaded;
};

#endif
