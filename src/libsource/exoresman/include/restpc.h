#ifndef CRESTPC_H
#define CRESTPC_H

// The BioWare texture (.tpc) resource wrapper parses the TPC header, walks the mipmap chain and
// publishes views of the header, pixel data and trailing TXI block.

#include "exoresman.h"

// TPC file header. Only the leading fields are decoded; the rest of the fixed-size header region is
// reserved.
struct TPCHeader {
    unsigned int   m_nDataSize;   // nonzero means compressed (raw pixel byte count)
    float          m_fAlphaTest;
    unsigned short m_width;
    unsigned short m_height;
    unsigned char  m_formatBits;  // bits 0/1/2 select the pixel format (1/3/4)
    unsigned char  m_nMipCount;
    unsigned char  m_reserved[0x80 - 0x0e];  // undecoded remainder of the header region
};

class CResTPC : public CRes {
public:
    CResTPC();
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 6 slots
    virtual ~CResTPC();  // slots 0-1 (D2+D0)
    virtual int OnResourceFreed();
    virtual int OnResourceServiced();
    // </VTABLE-GEN>

    int   GetTPCAttrib(int* pWidth, int* pHeight, char* pFormat, int* pnCompressedSize, int* pnUncompressedSize,
                       int* pTXISize, float* pAlphaTest, char* pMipCount);
    void* GetTPCDataPtr();
    void* GetTPCHeaderPtr();
    void* GetTPCTXIPtr();
    int   GetTPCSize();
    int   GetTPCTXISize();
    int   IsCompressed();
    int   IsLoaded();

    int          m_bCompressed;
    int          m_bLoaded;
    int          m_nUncompressedSize;      // uncompressed pixel size, the answer when not compressed
    int          m_nCompressedSize;      // compressed pixel size, the answer when compressed
    int          m_nTXISize;
    void*        m_pTPCData;     // base buffer past the header
    void*        m_pTPCHeader;   // base buffer, TPCHeader*
    void*        m_pTPCTXI;      // trailing TXI block
};

#endif
