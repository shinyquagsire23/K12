// The Targa (.tga) texture resource wrapper. It decodes the image into its own heap buffer rather
// than publishing a view into the file data.

#ifndef CRESTGA_H
#define CRESTGA_H

#include "exoresman.h"
#include "exostring.h"

// The on-disk TGA header's size, and an RLE packet byte: a run flag over a count less one (the TGA,
// PLT and font decoders share the encoding).
enum {
    TGA_HEADER_SIZE = 18,
    RLE_COUNT_MASK = 0x7f,
    RLE_RUN_FLAG = 0x80,
};

// The on-disk TGA header, deliberately left unpacked. The colour-map spec is unaligned in the file,
// but packing the struct degrades the aligned width/height reads.
struct TGAHeader {
    unsigned char  m_idLength;
    unsigned char  m_colorMapType;
    unsigned char  m_imageType;
    unsigned char  m_abColorMapSpec[5];
    unsigned short m_xOrigin;
    unsigned short m_yOrigin;
    unsigned short m_width;
    unsigned short m_height;
    unsigned char  m_bitsPerPixel;
    unsigned char  m_descriptor;
};

// Byte count the colour map occupies in the file: `(entry bits / 8) * entry count`.
inline unsigned int GetTGAColorMapSize(const TGAHeader* h)
{
    return (h->m_abColorMapSpec[4] >> 3) * *reinterpret_cast<const unsigned short*>(&h->m_abColorMapSpec[2]);  // raw-offset: TGA file header
}

class CResTGA : public CRes {
public:
    CResTGA();
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 6 slots
    virtual ~CResTGA();  // slots 0-1 (D2+D0)
    virtual int OnResourceFreed();
    virtual int OnResourceServiced();
    // </VTABLE-GEN>

    int   CopyTGAData(unsigned char* pDst);
    int   GetTGAAttrib(unsigned int* pWidth, unsigned int* pHeight,
                       unsigned char* pBitsPerPixel);
    void* GetTGAColorMapPtr();
    void* GetTGADataPtr();
    void* GetTGAHeaderPtr();
    int   GetTGASize();
    int   IsColorMapped();
    int   IsCompressed();
    int   IsLoaded();

    int         Write(const CExoString& path);
    int         ReadColorMappedRLETGA();
    int         ReadUnmappedRLETGA();

    int          m_bDataAllocated;
    int          m_bColorMapped;
    int          m_bCompressed;
    int          m_bLoaded;
    unsigned int m_nTGASize;
    unsigned int m_nTGABlobSize;
    void* m_pTGAColorMap;
    void* m_pTGAData;
    void* m_pTGAHeader;
};

#endif
