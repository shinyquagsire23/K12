#ifndef CRES4PC_H
#define CRES4PC_H

// A compressed-texture (.4pc) resource. Near-identical to CResDDS, but the header is four
// dwords with no trailing float and the payload begins right after it.

#include "exoresman.h"

// The .4pc header parsed at the front of the file buffer. All four dwords are byte-swapped on
// load; the third is treated as a float.
struct Header4PC {
    unsigned int m_nWidth;
    unsigned int m_nHeight;
    float        m_fAlphaTest;
    unsigned int m_nFormat;
};

class CRes4PC : public CRes {
public:
    CRes4PC();
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 6 slots
    virtual ~CRes4PC();  // slots 0-1 (D2+D0)
    virtual int OnResourceFreed();
    virtual int OnResourceServiced();
    // </VTABLE-GEN>

    int   Copy4PCData(unsigned char* pDst);
    int   Get4PCAttrib(unsigned int* pnWidth, unsigned int* pnHeight, float* pfAlphaTest, int* pnFormat);
    void* Get4PCDataPtr();
    void* Get4PCHeaderPtr();
    int   Get4PCSize();
    int   IsLoaded();

    int          m_bLoaded;
    unsigned int m_n4PCSize;
    void*        m_p4PCData;     // payload, past the header
    void*        m_p4PCHeader;   // base buffer
};

#endif
