#ifndef CRESFNT_H
#define CRESFNT_H

#include "exoresman.h"

// A Windows bitmap font (.fnt) resource. The resource carries two blobs, the glyph metrics (FNT)
// and the bitmap (TGA), which the accessors hand out separately.

// The 18-byte uncompressed-TGA header at the front of the bitmap blob. It is not packed; the
// colour-map spec is unaligned in the file, so it stays a byte array and the rest lands on natural
// offsets.
struct HeaderTGA {
    unsigned char  nIdLength;
    unsigned char  nColorMapType;
    unsigned char  nImageType;
    unsigned char  aColorMapSpec[5];  // first entry index, length, entry size
    unsigned short nXOrigin;
    unsigned short nYOrigin;
    unsigned short nWidth;
    unsigned short nHeight;
    unsigned char  nBitsPerPixel;
    unsigned char  nImageDescriptor;
};

// The FNT half of a .fnt resource, a glyph count followed by five metrics, then the glyph records.
// Both halves are views into the resource buffer, byte-swapped in place rather than copied.
struct HeaderFNT {
    int   nGlyphCount;    // 16-byte glyph records following the metrics
    float afMetrics[5];
};

class CResFNT : public CRes {
public:
    CResFNT();
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 6 slots
    virtual ~CResFNT();  // slots 0-1 (D2+D0)
    virtual int OnResourceFreed();
    virtual int OnResourceServiced();
    // </VTABLE-GEN>

    // Set on the RLE path only, and the sole guard on the bitmap buffer's delete[]: the bitmap is
    // then a heap buffer we own rather than a view into the file data.
    int   m_bTGADataOwned;
    int   m_bColorMapped;
    int   m_bCompressed;
    int   m_bLoaded;
    unsigned int m_fntSize;
    unsigned int m_tgaSize;        // decompressed pixel bytes, width * height * (bpp / 8)
    unsigned int m_nTGABlobSize;   // raw in-file bitmap blob length, header excluded
    void* m_pTGAColorMap;
    void* m_pTGAData;
    void* m_pTGAHeader;
    void* m_pFNTData;
    void* m_pFNTHeader;

    int   IsColorMapped();
    int   IsCompressed();
    int   IsLoaded();
    int   GetFNTSize();
    int   GetTGASize();
    void* GetTGAColorMapPtr();
    void* GetTGADataPtr();
    void* GetTGAHeaderPtr();
    void* GetFNTDataPtr();
    void* GetFNTHeaderPtr();

    int   CopyFNTData(unsigned char* pDst);
    int   CopyTGAData(unsigned char* pDst);
    // Reads width, height and bits per pixel out of the TGA header. Checks m_pFNTHeader rather than
    // m_pTGAHeader to decide whether the font is loaded.
    int   GetTGAAttrib(unsigned int* pWidth, unsigned int* pHeight, unsigned char* pBitsPerPixel);

    int   ReadColorMappedRLETGA();
    int   ReadUnmappedRLETGA();
};

#endif
