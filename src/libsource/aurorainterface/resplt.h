#ifndef CRESPLT_H
#define CRESPLT_H

// The palette-layered-texture (.plt) resource. The payload may be RLE-compressed, in which case
// it is decompressed into a buffer this object owns.

#include "exoresman.h"

// The header parsed at the front of the file buffer; all six dwords are byteswapped.
struct PLTHeader {
    unsigned int m_magic;
    unsigned int m_nVersion;
    unsigned int m_nNumLayers;
    unsigned int m_bCompressed;
    unsigned int m_width;
    unsigned int m_height;
};

class CResPLT : public CRes {
public:
    CResPLT();
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 6 slots
    virtual ~CResPLT();  // slots 0-1 (D2+D0)
    virtual int OnResourceFreed();
    virtual int OnResourceServiced();
    // </VTABLE-GEN>

    int   CopyPLTData(unsigned char* pDst);
    int   GetPLTAttrib(unsigned int* pWidth, unsigned int* pHeight, unsigned int* pNumLayers);
    void* GetPLTDataPtr();
    void* GetPLTHeaderPtr();
    int   GetPLTSize();
    int   IsCompressed();
    int   IsLoaded();
    int   ReadRLEPLT();

    int          m_bOwnsData;
    int          m_bCompressed;
    int          m_bLoaded;
    unsigned int m_nPLTSize;
    unsigned int m_nSrcSize;
    void*        m_pPLTData;
    void*        m_pPLTHeader;
};

#endif
