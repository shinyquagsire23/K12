    CSWSMessage();

    // Declared here for the call sites; the codecs live in another translation unit.
    void WriteOBJECTIDServer(unsigned long long objectId);
    unsigned long long ReadOBJECTIDServer();
    void WriteCExoLocStringServer(CExoLocString& s, unsigned char nLang);

    // Admin-token parsers, dispatched from HandleServerAdminToServerMessage.
    int ParseToken(char const* pToken, unsigned char** ppBuffer, unsigned int& nSize,
                   int nDelim);
    int ParseGetString(unsigned char* pBuffer, unsigned int nSize, CExoString& sResult,
                       unsigned int nMaxLen);
    int ParseGetBool(unsigned char* pBuffer, unsigned int nSize, int& nResult);

    // -- inbound (player to server) handlers --
    // Each handler returns whether the message was consumed.
    int HandlePlayerToServerServerStatusMessage(CSWSPlayer* pPlayer, unsigned char nType);
    int HandlePlayerToServerServerChatMessage(CSWSPlayer* pPlayer, unsigned char nType);
    // Four-way dispatch on the map-pin sub-opcode; unknown opcodes return 1.
    int HandlePlayerToServerQuickChatMessage(CSWSPlayer* pPlayer, unsigned char nType);
    int SendServerToPlayerQuickChatMessage(unsigned long long objectId,
                                           unsigned short nChat);
    int HandlePlayerToServerMapPinMessage(CSWSPlayer* pPlayer, unsigned char nType);
    int HandlePlayerToServerMapPinSetMapPinAt(CSWSPlayer* pPlayer);
    int HandlePlayerToServerMapPinDestroyMapPin(CSWSPlayer* pPlayer);
    int HandlePlayerToServerMapPinChangePin(CSWSPlayer* pPlayer);
    // Reads an action byte and a creature id, then, for nType == 1 only, permission-gates the
    // display change, adjusts both creatures' m_nCharSheetViewers counters and swaps the
    // char-sheet GUI to the new creature.
    int HandlePlayerToServerCharacterSheetMessage(CSWSPlayer* pPlayer, unsigned char nType);
    int HandlePlayerToServerCharacterDownload(CSWSPlayer* pPlayer, unsigned char nType);
    int SendServerToPlayerCharacterDownloadReply(CSWSPlayer* pPlayer);
    int SendServerToPlayerCharacterDownloadFail(CSWSPlayer* pPlayer);
    // The send is the tail of a character-load path. nMode selects where the .bic comes from
    // (1 = a resource directly, 4 = the module IFO's Mod_PlayerList, 5 = the server vault), and
    // the same byte is echoed back in the payload.
    int SendServerToPlayerUpdateCharResponse(CSWSPlayer* pPlayer, unsigned char nMode,
                                             CResRef cResRef);
    int HandlePlayerToServerShutDownServer(CSWSPlayer* pPlayer, unsigned char nType);
    int HandlePlayerToServerPlayModuleCharacterList_Stop(CSWSPlayer* pPlayer);
    // Sub-opcode dispatcher for the pair below (1 == _Start, 2 == _Stop, anything else 0).
    int HandlePlayerToServerPlayModuleCharacterList(CSWSPlayer* pPlayer, unsigned char nType);
    // Broadcasts one _Response per connected player that owns a valid game object, then latches
    // the requester's m_bPlayModuleListingCharacters.
    int HandlePlayerToServerPlayModuleCharacterList_Start(CSWSPlayer* pPlayer);
    // Queues a script event against the dead creature, with the module as context object.
    int HandlePlayerToServerPlayerDeath(CSWSPlayer* pPlayer, unsigned char nType);
    // Handles the client driving its own creature: heading plus two flag bytes, then, if the
    // creature is commandable and not in transit, reset combat state and queue a drive action.
    int HandlePlayerToServerInputDriveControl(CSWSPlayer* pPlayer);
    __attribute__((noinline))
    int HandlePlayerToServerInputAbortDriveControl(CSWSPlayer* pPlayer);
    // Cancels a running GUI timing bar: only a creature flagged m_bCommandable has its action
    // queue cleared.
    int HandlePlayerToServerInputCancelGuiTimingEvent(CSWSPlayer* pPlayer);
    // Handles the walk-to-waypoint drive command: waypoint id, a point, path id, two flags, a
    // goal-within-reach byte and a target id. Returns 0 when the walk is refused.
    int HandlePlayerToServerInputWalkToWaypoint(CSWSPlayer* pPlayer);
    // The group twin of InputWalkToWaypoint walks the party lead to the given point and id instead
    // of the player's own creature. Without combat the path is ClearAllActions(1), ActionManager(8)
    // and AddMoveToPointAction.
    int HandlePlayerToServerGroupInputWalkToWaypoint(CSWSPlayer* pPlayer, CSWSCreature* pCreature,
        unsigned long long nId, float fX, float fY, float fZ, unsigned char bFlag,
        int a, int b, unsigned long long c);
    // One flag byte, straight into the player's inventory-GUI tracker. Sub-opcode 1 only.
    int HandlePlayerToServerGuiInventoryMessage(CSWSPlayer* pPlayer, unsigned char nType);
    // The container twin reads the container's object id and one flag, then dispatches
    // CloseInventory on whichever object type the id resolves to. Sub-opcode 2 only.
    int HandlePlayerToServerGuiContainerMessage(CSWSPlayer* pPlayer, unsigned char nType);
    // -- the big dispatcher's one-line case callees. Each reads its fields off the packet and
    // returns whether the message was consumed; Gold and Death discard that result.
    int HandlePlayerToServerLoginMessage(CSWSPlayer* pPlayer, unsigned char nType);
    int HandlePlayerToServerModuleMessage(CSWSPlayer* pPlayer, unsigned char nType);
    int HandlePlayerToServerAreaMessage(CSWSPlayer* pPlayer, unsigned char nType);
    int HandlePlayerToServerGameObjectUpdate(CSWSPlayer* pPlayer, unsigned char nType);
    int HandlePlayerToServerInputMessage(CSWSPlayer* pPlayer, unsigned char nType);
    int HandlePlayerToServerGoldMessage(CSWSPlayer* pPlayer, unsigned char nType);
    int HandlePlayerToServerChatMessage(CSWSPlayer* pPlayer, unsigned char nType);
    int HandlePlayerToServerInventoryMessage(CSWSPlayer* pPlayer, unsigned char nType);
    int HandlePlayerToServerParty(CSWSPlayer* pPlayer, unsigned char nType);
    int HandlePlayerToServerCheatMessage(CSWSPlayer* pPlayer, unsigned char nType);
    int HandlePlayerToServerCharListMessage(CSWSPlayer* pPlayer, unsigned char nType);
    int HandlePlayerToServerDialogMessage(CSWSPlayer* pPlayer, unsigned char nType);
    int HandlePlayerToServerJournalMessage(CSWSPlayer* pPlayer, unsigned char nType);
    int HandlePlayerToServerLevelUpMessage(CSWSPlayer* pPlayer, unsigned char nType);

    // -- message builders --
    void AddDoorAppearanceToMessage(CSWSDoor* pDoor);
    // Appearance row, mesh state and seven interaction flags, then one bit saying whether the
    // placeable's Description locstring resolves to anything.
    void AddPlaceableAppearanceToMessage(CSWSPlaceable* pPlaceable);
    // The item twin of AddDoorAppearanceToMessage writes the base-item row, then one appearance
    // byte, plus two more only for base items whose model scheme is the multi-part one.
    void AddItemAppearanceToMessage(CSWSItem* pItem);
    void AddAreaOfEffectObjectToMessage(CSWSAreaOfEffectObject* pAreaOfEffect);
    // The trigger's polygon, one vertex at a time.
    void AddTriggerGeometryToMessage(CSWSTrigger* pTrigger);
    void AddActiveItemPropertiesToMessage(CSWSItem* pItem, CSWSCreature* pCreature);

    // True when equipment slot nSlot differs from the snapshot this client was last sent. The
    // subject is the player's own creature unless the in-game GUI is showing a party member.
    int ComputeInventoryUpdateRequired(CSWSPlayer* pPlayer, unsigned int nSlot);

    // -- last-update / visibility bookkeeping --
    int ComputeRepositoryUpdateRequired(CSWSPlayer* pPlayer, CExoLinkedListNode* pA,
                                        CExoLinkedListNode* pB);
    // True when both lists have the same length and are element-wise equal.
    int CompareCreatureLists(CExoArrayList<unsigned long long>* pA,
                             CExoArrayList<unsigned long long>* pB);
    // Source first, destination second.
    void AssignCreatureLists(CExoArrayList<unsigned long long>* pSrc,
                             CExoArrayList<unsigned long long>* pDst);
    // Tests two looping-visual-effect lists for set equality; each entry needs a partner in the
    // other.
    int  CompareVisualEffectLists(CExoArrayList<CLoopingVisualEffect*>* pA,
                                  CExoArrayList<CLoopingVisualEffect*>* pB);
    // Destination first, source second.
    void AssignVisualEffectLists(CExoArrayList<CLoopingVisualEffect*>* pDst,
                                 CExoArrayList<CLoopingVisualEffect*>* pSrc);
    // Both spell-memorization hooks return 0: KOTOR has no memorized-spell system, so these
    // NWN-inherited entry points are stubs. The middle test of GuiSkills calls GetCanUseSkill
    // twice with the same argument and ORs the results, which is a bug kept as-is.
    int ComputeLastUpdate_GuiSkills(CSWSCreature* pCreature);
    // The player-state word the client GUI mirrors.
    int ComputeLastUpdate_PlayerState(CSWSCreature* pCreature);
    int ComputeLastUpdate_GuiMemorizedSpells(CSWSCreature* pCreature,
                                             CSWSPlayerLastUpdateObject* pLast);
    int ComputeLastUpdate_GuiNumberMemorizedSpells(CSWSCreature* pCreature,
                                                   CSWSPlayerLastUpdateObject* pLast);
    // Packs the party/associate GUI state byte: bit 0 detect mode, bit 1 the m_stealthMode solo
    // latch, bits 2-7 the six reported combat modes.
    char ComputeLastUpdate_AssociateState(CSWSCreature* pCreature);
    // Diffs all three feat lists against the snapshot. The two id lists are searched while the
    // remaining-uses list is compared index by index.
    int  ComputeLastUpdate_GuiFeats(CSWSCreature* pCreature,
                                    CSWSPlayerLastUpdateObject* pLast);
    // Per-class remaining spell uses, diffed against the snapshot for every Jedi class slot.
    int  ComputeLastUpdate_GuiKnownSpellUses(CSWSCreature* pCreature,
                                             CSWSPlayerLastUpdateObject* pLast);
    // Diffs the live spell-like-ability list against the snapshot's lazily-allocated copy.
    int  ComputeLastUpdate_CompareSpellLikeAbility(CSWSCreature* pCreature,
                                                   CSWSPlayerLastUpdateObject* pLast);
    // A writer despite the ComputeLastUpdate_ prefix. It allocates the snapshot's container on
    // first use and deep-copies the live list into it.
    void ComputeLastUpdate_StoreUpdateSpellLikeAbility(CSWSCreature* pCreature,
                                                       CSWSPlayerLastUpdateObject* pLast);
    // Also a writer despite the name; writes the spell-like-ability delta into the frame.
    void ComputeLastUpdate_WriteSpellLikeAbility(CSWSCreature* pCreature,
                                                 CSWSPlayerLastUpdateObject* pLast);

    // Argument order differs across these three: StoreValues takes (pLast, pObject) while both of
    // its callees take (pObject, pLast).
    void StoreValuesInLastUpdateObject(CSWSPlayer* pPlayer, CLastUpdateObject* pLast,
                                       CSWSObject* pObject, unsigned int a,
                                       unsigned int b);
    void UpdateLastUpdateObject(CSWSPlayer* pPlayer, CSWSObject* pObject,
                                CLastUpdateObject* pLast, unsigned int a);
    void UpdateLastUpdateObjectAppearance(CSWSObject* pObject, CLastUpdateObject* pLast,
                                          unsigned int nMask);
    int  ComputeAppearanceUpdateRequired(CSWSObject* pObject,
                                         CLastUpdateObject* pLast);
    int  ComputeUpdateRequired(CSWSPlayer* pPlayer, CSWSObject* pObject,
                               CLastUpdateObject* pLast, int a);
    CLastUpdateObject* CreateNewLastUpdateObject(CSWSPlayer* pPlayer, CSWSObject* pObject,
                                                 unsigned int* pnUpdateType,
                                                 unsigned int* pnUpdateFlags);
    void TestObjectUpdateDifferences(CSWSPlayer* pPlayer, CSWSObject* pObject,
                                     CLastUpdateObject** ppLastUpdateObject,
                                     unsigned int* pnUpdateType,
                                     unsigned int* pnUpdateFlags);
    int  TestObjectVisible(CSWSObject* pObject, CSWSObject* pObject2);
    void DeleteLastUpdateObjectsForObject(CSWSPlayer* pPlayer,
                                          unsigned long long objectId);
    int  ComputeVisibilityLists(CSWSCreature* pCreature,
                                CSWSPlayerLastUpdateObject* pLast);

    // In the action-queue snapshot pair, Compute* diffs the live queue against the snapshot,
    // Update* copies the live queue over it. Both walk the creature's CSWActionQueueEntry array and
    // the snapshot's.
    int  ComputeLastUpdate_ActionQueue(CSWSCreature* pCreature,
                                       CSWSPlayerLastUpdateObject* pLast);
    void UpdateLastUpdateActionQueue(CSWSCreature* pCreature,
                                     CSWSPlayerLastUpdateObject* pLast);
    void UpdateLastUpdateVisibilityList(CSWSCreature* pCreature,
                                        CSWSPlayerLastUpdateObject* pLast);

    // -- per-panel GameObjUpdate writers --
    int  WriteGameObjUpdate_MinorGUIPanels(CSWSPlayer* pPlayer);
    // The inventory-slot pair, add and delete, has near-identical frames.
    void WriteGameObjUpdate_WriteInventorySlotAdd(CSWSCreature* pCreature, CSWSItem* pItem,
                                                  unsigned int nSlot);
    void WriteGameObjUpdate_WriteInventorySlotDelete(CSWSCreature* pCreature,
                                                     unsigned int nSlot);
    void WriteGameObjUpdate_UpdateAppearance(CSWSObject* pObject, CLastUpdateObject* pLast,
                                             unsigned int nMask);
    void WriteGameObjUpdate_CharacterSheet(CSWSPlayer* pPlayer, unsigned int nMask);

    // ForYourself forwards all four arguments unchanged.
    void ComputeGameObjectUpdateForYourself(CSWSPlayer* pPlayer, CSWSObject* pObject,
                                            CGameObjectArray* pArray,
                                            unsigned long long objectId);
    void ComputeGameObjectUpdateForObject(CSWSPlayer* pPlayer, CSWSObject* pObject,
                                          CGameObjectArray* pArray,
                                          unsigned long long objectId);

    // -- the GameObjUpdate frame's own helpers --
    // Drops the player's snapshot entries for objects that are no longer in their area.
    void DeleteLastUpdateObjectsInOtherAreas(CSWSPlayer* pPlayer);
    // Buckets one candidate object into a GameObjUpdate category: the viewer itself, a creature in
    // or out of combat, a trigger, a door, an item, a non-static placeable, an area of effect, or a
    // value meaning "do not replicate".
    unsigned int SelectCategoryForGameObject(CGameObject* pGameObject,
                                             CSWSObject* pObject);
    // Builds the per-frame distance-sorted work list. Returns an array whose element count comes
    // back through pnCount; the array is freed with delete[].
    CSWSPlayerLUOSortedObjectList*
         SortObjectsForGameObjectUpdate(CSWSPlayer* pPlayer, CSWSObject* pObject,
                                        CGameObjectArray* pArray, int* pnCount);
    // Ships as much of one category of the work list as the byte budget allows; returns nonzero
    // when it ran out of room, which is what stops the frame's category ladder.
    int  ComputeGameObjectUpdateForCategory(unsigned int nCategory, unsigned int nBudget,
                                            CSWSPlayer* pPlayer, CSWSObject* pObject,
                                            CGameObjectArray* pArray,
                                            CSWSPlayerLUOSortedObjectList* pSorted,
                                            int nCount);
    // Closes the frame with the "how far did we get" code.
    void WriteGameObjUpdate_WorkRemaining(CSWSObject* pObject, CSWSArea* pArea, int nStage,
                                          int nStageCount);
    void WriteGameObjUpdate_MajorGUIPanels(CSWSPlayer* pPlayer);
    // The player-panel snapshot trio MajorGUIPanels drives. Test diffs the viewed creature's
    // panels against the snapshot and hands back a change mask by reference; PlayerUpdate ships
    // the changed panels; Store writes the new values back.
    void TestPlayerUpdateDifferences(CSWSPlayer* pPlayer, CSWSPlayerLastUpdateObject* pLast,
                                     CLastUpdateObject* pLastObj,
                                     unsigned int& nMask);
    void WriteGameObjUpdate_PlayerUpdate(CSWSPlayer* pPlayer,
                                         CSWSPlayerLastUpdateObject* pLast,
                                         CLastUpdateObject* pLastObj,
                                         unsigned int nMask);
    void StoreValuesInLastPlayerUpdateObject(CSWSPlayer* pPlayer,
                                             CSWSPlayerLastUpdateObject* pLast,
                                             CLastUpdateObject* pLastObj,
                                             unsigned int nMask);
    int  ComputeLastUpdate_GuiKnownSpells(CSWSCreature* pCreature,
                                          CSWSPlayerLastUpdateObject* pLast);
    // Stamps slot nSlot's live item id and stack count into the player's inventory snapshot.
    void UpdateLastUpdateInventory(CSWSPlayer* pPlayer, unsigned int nSlot);
    // Ships one container's contents as a repository diff against the client's snapshot. pPlayer
    // is unused. nList selects the CSWSPlayerLUOInventory list (0 container, 1 repository, 2
    // store) rather than being a flag word.
    void WriteRepositoryUpdate(CSWSPlayer* pPlayer, CSWSObject* pObject,
                               CItemRepository* pRepository,
                               CSWSPlayerLUOInventory* pInventory,
                               unsigned char nList, char nOpcode);
    int  WriteGameObjUpdate_PartyAIState(CSWSPlayer* pPlayer);
    // In the party-snapshot pair PartyAIState drives, Test diffs one member against its snapshot,
    // allocating the record on first sight, and hands back both the record and a change mask; Store
    // writes the new values back under that mask.
    void TestPartyObjectUpdateDifferences(CSWSPlayer* pPlayer, CSWSCreature* pCreature,
                                          CLastUpdatePartyObject** ppLast,
                                          unsigned int* pnMask);
    void StoreValuesInLastUpdatePartyObject(CSWSCreature* pViewerCreature,
                                            CLastUpdatePartyObject* pLast,
                                            CSWSCreature* pCreature,
                                            unsigned int nMask);
    void WriteGameObjUpdate_UpdateObject(CSWSPlayer* pPlayer, CSWSObject* pObject,
                                         CLastUpdateObject* pLast, unsigned int nMask,
                                         unsigned int a);

    int SendServerToPlayerParty_Invite(unsigned int nPlayerId,
                                       unsigned long long objectId);

    // -- journal --
    // Sends one whole journal quest: identity, progress and the localized text to show. The
    // trailing scalars are SJournalEntry fields passed one by one rather than as the struct, with
    // one parameter per field the entry reads.
    int SendServerToPlayerJournalAddQuest(CSWSPlayer* pPlayer, const CExoString& sPlotId,
                                          int nState, unsigned int nPriority,
                                          unsigned short nPicture, int bEnd,
                                          unsigned int nDate, unsigned int nTime,
                                          CExoLocString& locName, CExoLocString& locText,
                                          int nPlotIndex, int nPlanetId,
                                          int nQuestEntryXP);
    // Sends the lighter "an existing quest changed" notification.
    int SendServerToPlayerJournalUpdated(CSWSPlayer* pPlayer, int a, int bEnd,
                                         CExoLocString& locName);

    // -- module / load-save / login --
    // The three-byte sends allocate the header, stamp the marker byte, the message category (login,
    // module, dialog, death GUI) and the sub-opcode, send, then free.
    // ---------------------------------------------------------------------------------------
    // The payload send family and its hub. Each member builds a write message and hands the
    // finished buffer to SendServerToPlayerMessage, which stamps the same three header bytes over
    // its start. A member with no payload degenerates to the bare three-byte header.
    int SendServerToPlayerMessage(unsigned int nPlayerId, unsigned char nCategory,
                                  unsigned char nSubOpcode, unsigned char* pMsg,
                                  unsigned int nSize);
    // The inventory drag/drop protocol. Every member is (playerId, objectId).
    int SendServerToPlayerInventory_Drop(unsigned int nPlayerId,
                                         unsigned long long objectId);
