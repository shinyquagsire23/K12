class CSWInventory {
public:
    // Slot bits: 1 << the slot's INVENTORY_SLOT_* index. GetItemInSlot and the equip paths take
    // these, not the index.
    enum {
        SLOT_HEAD         = 1 << 0,
        SLOT_BODY         = 1 << 1,
        SLOT_HANDS        = 1 << 3,
        SLOT_RIGHTWEAPON  = 1 << 4,
        SLOT_LEFTWEAPON   = 1 << 5,
        SLOT_LEFTARM      = 1 << 7,
        SLOT_RIGHTARM     = 1 << 8,
        SLOT_IMPLANT      = 1 << 9,
        SLOT_BELT         = 1 << 10,
        SLOT_CWEAPON_L    = 1 << 14,
        SLOT_CWEAPON_R    = 1 << 15,
        SLOT_CWEAPON_B    = 1 << 16,
        SLOT_CARMOUR      = 1 << 17,
        SLOT_RIGHTWEAPON2 = 1 << 18,
        SLOT_LEFTWEAPON2  = 1 << 19,
    };

    CSWInventory();
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 2 slots
    virtual ~CSWInventory();  // slots 0-1 (D2+D0)
    // </VTABLE-GEN>
#if KOTOR1  // K1: 18 item slots (the two claw slots are K2-only)
    unsigned long long m_aItemOids[18];
#else
    unsigned long long m_aItemOids[20];
#endif
    // The slot argument is an INVENTORY_SLOT_* bit (1 << n), not an index; the stored
    // object id is resolved through the server's object array.
    CSWSItem* GetItemInSlot(unsigned int nSlot);
    // The address of a slot's stored object id, or null.
    unsigned long long* GetSlotPointer(unsigned int nSlot);
    int      GetItemInInventory(CSWSItem* pItem);
    // Slot index for a base-item type; 2 is the armour slot.
    int      FindSlot(unsigned int nBaseItem);
    // Returns the slot BIT (1 << n), not an index.
    unsigned int GetSlotFromItem(CSWSItem* pItem);
    void     PutItemInSlot(unsigned int nSlot, CSWSItem* pItem);
    // Returns 1 when the item was found and removed.
    int      RemoveItem(CSWSItem* pItem);
};

