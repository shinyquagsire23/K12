// Per-player character-sheet GUI tracker: which creature's sheet is displayed, and the snapshot it is
// diffed against.
class CSWSPlayerCharSheetGUI {
public:
    // m_nAction: which group of fields ComputeCharacterSheetUpdateRequired re-diffs.
    enum {
        ACTION_STATS  = 0,
        ACTION_SKILLS = 1,
        ACTION_FEATS  = 2,
    };

    unsigned long long m_objectId;
    // The client's last character-sheet action byte, which also selects the fields re-diffed.
    char m_nAction;
    char _pad9[0x10 - 0x9];
    // Owned; rebuilt on every display change.
    CSWCreatureStatsUpdate* m_pStatsUpdate;
    int m_nReserved1;

    // Mask of the character-sheet fields that changed, fed straight to the reply writer.
    int ComputeCharacterSheetUpdateRequired(CSWSPlayer* pPlayer);
    void SetCreatureDisplayed(unsigned long long objectId);

    CSWSPlayerCharSheetGUI();

    ~CSWSPlayerCharSheetGUI();
};

// The inventory snapshot the GUI wrapper below owns.
class CSWSPlayerLUOInventory;

// Per-player inventory GUI tracker.
class CSWSPlayerInventoryGUI {
public:
    CSWSPlayerLUOInventory* m_pInventory;
    // Closing the panel discards the slots and repository the client was last told about.
    int m_bOpen;

    CSWSPlayerInventoryGUI();
    ~CSWSPlayerInventoryGUI();
    void SetOpen(int bOpen);
};

// Per-player container GUI tracker: which container the client has open.
class CSWSPlayerContainerGUI {
public:
    unsigned long long m_objectId;
    int m_bOpen;

    CSWSPlayerContainerGUI();
    void SetOpen(CSWSPlayer* pPlayer, unsigned long long objectId, int bOpen);
};

// Base of CSWSPlayer. Nothing constructs one on its own.
class CSWSClient {
public:
    CSWSClient(unsigned int nPlayerId);

    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 3 slots
    virtual ~CSWSClient();  // slots 0-1 (D2+D0)
    virtual CSWSPlayer* AsSWSPlayer();
    // </VTABLE-GEN>

    unsigned int m_nPlayerId;
    int          m_nLanguage;
};

// One per connected client: connection state, the creature it drives, and the GUI state mirrored back
// to it.
class CSWSPlayer : public CSWSClient {
public:
    CSWSPlayer(unsigned int nPlayerId);

    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 3 slots
    virtual ~CSWSPlayer();
    virtual CSWSPlayer* AsSWSPlayer() { return this; }
    // </VTABLE-GEN>

    CExoLinkedList<CLastUpdateObject>* m_pLastUpdateObjectList;
    CExoLinkedList<CLastUpdatePartyObject>* m_pLastUpdatePartyObjectList;
    // Loading-screen selection; an id of 1 means m_sAreaTransitionBMP names a custom bitmap. -1 and 1
    // both mean "not chosen yet", 0 picks one at random.
    int        m_nAreaTransitionBMP;
    char       _pad24[0x28 - 0x24];
    CExoString m_sAreaTransitionBMP;
    unsigned int m_bCheatToggle;
    // 1 while connecting, 2 once in game.
    unsigned char m_connectionState;
    char _pad3d[0x40 - 0x3d];
    // The object this player is driving, kept in step with the area refcounts by SetGameObject.
    // Normally the same id as m_gameObjectId, but maintained separately.
    unsigned long long m_oidSWSObject;
    unsigned long long m_lastGameObjUpdateTime;
    unsigned long long m_lastKnownAreaId;
    unsigned long long m_gameObjectId;
    int  m_bIsPrimaryPlayer;
    int  m_bRestoredPosition;
    int  m_playerIndex;
    int  m_bPlayModuleListingCharacters;

    // The journal sync state, allocated and initialized whole by the constructor.
    CSWSPlayerJournalState* m_pJournalState;

    CSWSPlayerCharSheetGUI* m_pCharSheetGUI;

    CSWSPlayerInventoryGUI* m_pInventoryGUI;
    CSWSPlayerContainerGUI* m_pContainerGUI;
    // Owned snapshot of the character sheet, spells, feats and action queue of the creature being
    // viewed. Distinct from the per-game-object list above.
    CSWSPlayerLastUpdateObject* m_pLastUpdateObject;
    int m_bInputModeReceived;
    // 3 or 4 while saving, 1 for an export reply.
    unsigned char m_state;
    CResRef m_resRef;
    char _padad[0xb4 - 0xad];
    int  m_characterLoaded;
    int  m_saveListIndex;
    char _padbc[0xc0 - 0xbc];

    CSWSObject* GetGameObject();
    void  SetGameObject(CSWSObject* pObject);
    // A player may only view the sheet of the creature it controls.
    int PermittedToDisplayCharacterSheet(unsigned long long objectId);
    // Reads the saved class line-up out of the module IFO, which the character-select screen needs
    // before anything is loaded. Returns 1 when the player entry exists; a missing class list is not a
    // failure.
    int GetCharacterInfoFromIFO(unsigned char& nClasses, int* pnClassIds,
                                unsigned char* pnClassLevels, unsigned int& nExperience);
    int   SaveServerCharacter();
    // The snapshot for one game object, or null when the client was never told about it.
    CLastUpdateObject* GetLastUpdateObject(unsigned long long id);
    // Replaces the panel snapshot and returns it, never null.
    CSWSPlayerLastUpdateObject* CreateNewPlayerLastUpdateObject();
    // Restores the creature from a saved IFO. A playerIndex of -1 selects the scratch copy in the temp
    // directory instead of the module's own IFO, and bRestorePosition only applies on the module-IFO
    // path.
    int   LoadCharacterFromIFO(unsigned int playerIndex, int bRestorePosition, int bPostProcess);
    void  ClearPlayerOnDestroyGame();
    // Wipes the panel snapshots but keeps the record.
    void  ClearPlayerLastUpdateObject();
    // Reads the character's GFF and stamps it onto the creature; 0 means loaded.
    int64_t  LoadCreatureData(CResRef resRef, CSWSCreature* pCreature);
    void  SetAreaTransitionBMP(int transitionId, const CExoString& bmp);
    // Packs the creature snapshot into the write buffer the export reply ships.
    int   PackCreatureIntoMessage();
    CExoString GetPlayerName();
    // Loads the character out of the server vault into a fresh creature; 0 means loaded.
    int64_t  LoadServerCharacter(CResRef c);
    // Single-player variant: as LoadServerCharacter with the resref fixed to "TEMP_CHAR", and it also
    // publishes the level and alignment to the global variable table.
    int64_t  LoadLocalCharacter();
    int   GetIsAllowedToSave();
};
