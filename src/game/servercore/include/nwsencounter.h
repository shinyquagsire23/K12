// Element of the encounter's spawn list.
class CEncounterListEntry {
public:
    CResRef       resRef;
    float         m_fCR;
    float         m_fPoints;
    int           m_bAlreadyUsed;
    int           m_bAlreadyChecked;
    int           m_bSingleSpawn;
#if !KOTOR1  // K1 has no "GuaranteedCount"
    int           m_nGuaranteedCount;
#endif

    CEncounterListEntry()
    {
        resRef = const_cast<char*>("");
        m_fCR = 0.0f;
        m_fPoints = 0.0f;
        m_bAlreadyUsed = 0;
        m_bAlreadyChecked = 0;
        m_bSingleSpawn = 0;
#if !KOTOR1
        m_nGuaranteedCount = 0;
#endif
    }

    // Non-trivial only for the array-new cookie; the body stays empty.
    ~CEncounterListEntry() {}
};

