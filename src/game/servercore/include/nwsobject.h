// One slot of the ten-entry action-queue snapshot the server keeps so it can tell the client's
// action-queue GUI what changed.
struct CSWActionQueueEntry {
    // The group and action ids of an empty slot.
    enum {
        SLOT_EMPTY = 0xffff,
    };

    unsigned short     m_nGroupId;

    unsigned short     m_nActionId;

    unsigned short     m_nAltActionId;

    int                m_nSpellId;

    Vector             m_vTarget;

    unsigned long long m_targetId;

    CSWActionQueueEntry()
    {
        m_nGroupId = SLOT_EMPTY;
        m_nActionId = SLOT_EMPTY;
        m_nAltActionId = SLOT_EMPTY;
        m_vTarget.x = 0.0f;
        m_vTarget.y = 0.0f;
        m_vTarget.z = 0.0f;
        m_targetId = OBJECT_INVALID;
        m_nSpellId = -1;
    }
};

