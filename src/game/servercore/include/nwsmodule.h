// The module's persistent identity record, straight out of the IFO's top level.
struct NWModuleID_st {
    unsigned char  m_id[32];
    int            m_nCreatorId;
    unsigned int   m_nVersion;
};

// The module's spawn point, as read out of the IFO.
class CSWSModuleEntryInfo {
public:
    CResRef m_entryArea;
    float   m_entryX;
    float   m_entryY;
    float   m_entryZ;
    float   m_entryDirX;
    float   m_entryDirY;
};

// One row of the module's tag to object-id lookup table. The buffer is 33 bytes: the engine's
// 32-character tag limit plus its terminator.
class CSWSTagNode {
public:
    char m_sTag[33];
    unsigned long long m_oid;
};

// The module's own IFO is the resource helper's held resource, kept open as a GFF for the module's
// whole lifetime; the IFO type derives from the GFF type, so every field read through it resolves to
// the inherited method unchanged.
class CSWSModule : public CResHelper<CResIFO, 2014>, public CGameObject {  // sizeof == 0x3b0
public:
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable (CResHelper<CResIFO, (unsigned short)2014>), 3 slots
    virtual ~CSWSModule();
    //   secondary vtable (CGameObject, offset-to-top -40), 29 slots; every slot but this one is
    //   inherited unchanged, and this one is the `_ZThn40_` adjusting thunk:
    virtual CSWSModule* AsSWSModule();
    // </VTABLE-GEN>
    // The game object's id is the module's own object id, handed to every script event as its caller.
    CExoLinkedList<NWModuleExpansion_st> m_expansionList;
    CExoLinkedList<NWModuleCutScene_st>  m_cutSceneList;
    CResRef    m_resRef;
    // The module's area object id, resolved on every use rather than cached here.
    unsigned long long m_oidArea;
    // The alternating half-tick latch, set after the area's AI update runs and cleared before the
    // module's own.
    int        m_bModuleUpdateTurn;
    char       _pad06c[0x70-0x6c];
    CExoLinkedList<NWPlayerListItem_st>  m_ifoPlayerList;
    CExoLocString m_sDescription;
    NWModuleID_st* m_pModuleID;
    // The IFO spawn point, not the module's area.
    CSWSModuleEntryInfo* m_pEntryInfo;
    // A colon-delimited "<name>:<suffix>" tag; the part after the colon becomes the save-file module
    // tag, or the whole field when there is no colon.
    CExoString m_sModuleResourceName;
    CExoLocString m_sName;
    // Constructed by the module constructor; nothing reads or writes it, and it is not the start
    // movie.
    CResRef    m_resHak;
    CResRef    m_startMovie;
    CSWSScriptVarTable m_scriptVarTable;
    // The module's own local-variable table, read by the module arm of GetLocalValue.
    CSWVarTable m_varTable;
    char       _pad124[0x128-0x124];

    // The module script block holds fifteen scripts of the same shape, so it is an array rather
    // than fifteen members. Each slot's name is its IFO label.
    enum {
        SCRIPT_HEARTBEAT = 0,        // Mod_OnHeartbeat
        SCRIPT_USER_DEFINED,         // Mod_OnUsrDefined
        SCRIPT_MODULE_LOAD,          // Mod_OnModLoad
        SCRIPT_MODULE_START,         // Mod_OnModStart
        SCRIPT_CLIENT_ENTER,         // Mod_OnClientEntr
        SCRIPT_CLIENT_LEAVE,         // Mod_OnClientLeav
        SCRIPT_ACTIVATE_ITEM,        // Mod_OnActvtItem
        SCRIPT_ACQUIRE_ITEM,         // Mod_OnAcquirItem
        SCRIPT_UNACQUIRE_ITEM,       // Mod_OnUnAqreItem
        SCRIPT_PLAYER_DEATH,         // Mod_OnPlrDeath
        SCRIPT_PLAYER_DYING,         // Mod_OnPlrDying
        SCRIPT_SPAWN_BUTTON_DOWN,    // Mod_OnSpawnBtnDn
        SCRIPT_PLAYER_REST,          // Mod_OnPlrRest
        SCRIPT_PLAYER_LEVEL_UP,      // Mod_OnPlrLvlUp
        SCRIPT_EQUIP_ITEM            // Mod_OnEquipItem, write-only: the reader is its sole user
    };
    CExoString m_aScript[15];

    // In the script-parameter block, each field below is written by one event-handler arm just
    // before it runs the script, so these are the get-last-X globals the module scripts read back.
    unsigned int m_lastUpdateDay;
    unsigned int m_lastUpdateTod;
    // The tag to object-id lookup table, with rows sorted by their lowercased tag and duplicates of
    // one tag contiguous.
    CExoArrayList<CSWSTagNode> m_tagTable;
    // A module-wide list of creature ids driven by the concealment effect handlers: applying
    // invisibility or sanctuary adds the creature's id and removing invisibility takes it out again.
    // Whether the list is really "concealed creatures" or something broader is unsettled.
    CExoArrayList<unsigned long long> m_playerList;
    int        m_nUserDefinedEventNumber;
    char       _pad244[0x248-0x244];
    unsigned long long m_oidEnteringClient;
    unsigned long long m_oidLeavingClient;
    unsigned long long m_oidAcquiredItem;
    unsigned long long m_oidItemAcquirer;
    unsigned long long m_oidUnAcquiredItem;
    unsigned long long m_oidItemUnAcquirer;
    unsigned long long m_oidRestingPlayer;
    unsigned char      m_nRestEventType;
    char       _pad281[0x288-0x281];
    unsigned long long m_oidDeadPlayer;
    unsigned long long m_oidDyingPlayer;
    unsigned long long m_oidSpawningPlayer;
    unsigned long long m_oidActivatedItem;
    unsigned long long m_oidItemActivator;
    unsigned long long m_oidItemActivateTarget;
    unsigned long long m_oidItemActivateTargetObject;   // a fourth activator-side id; role unconfirmed
    float      m_fActivateTargetX;
    float      m_fActivateTargetY;
    float      m_fActivateTargetZ;
    char       _pad2cc[0x2d0-0x2cc];
    unsigned long long m_oidLevelUpPlayer;
    // Seeded to the "no object" sentinel; nothing else touches it.
    unsigned long long m_oidReserved1;
    unsigned long long m_oidEquippedItem;
    // Real minutes per game hour, from the IFO.
    unsigned char m_nMinutesPerHour;
    // The dawn and dusk hours the time-of-day classifier compares the clock's hour against.
    unsigned char      m_nDawnHour;
    unsigned char      m_nDuskHour;
    // The IFO's start clock fields. On a fresh load these are out-parameters of the world-time query;
    // on a save load they come from the IFO.
    unsigned char      m_nStartMonth;
    unsigned char      m_nStartDay;
    unsigned char      m_nStartHour;
    unsigned char      m_nXPScale;
    char       _pad2ef[0x2f0-0x2ef];
    // The last calendar stamp shipped to the clients, in year, month, day, hour order.
    unsigned int       m_nLastCalendarYear;
    unsigned int       m_nLastCalendarMonth;
    unsigned int       m_nLastCalendarDay;
    unsigned int       m_nLastCalendarHour;
    // The sub-period elapsed counter. UpdateTime adds to this only while the clock sits in dawn or
    // dusk and resets it otherwise.
    unsigned int       m_nTimeOfDayElapsed;
    // The live world-clock period, as the day, night, dawn and dusk queries read it.
    unsigned char      m_nTimeOfDay;
    char       _pad305[0x308-0x305];
    // AIUpdate's own world-clock stamp, in the same day and time-of-day order as the pair above.
    unsigned int       m_nLastTimeDay;
    unsigned int       m_nLastTimeTod;
    // The IFO's save-game flag, read with its previous value as the default so it acts as a latch.
    // Nonzero gates the one-time primary-player load, the party creation, the saved-object-id
    // restore and the character-list packing.
    int        m_bIsSaveGame;
    char       _pad314[0x318-0x314];
    // The module's world journal, the log the client asks the server to append to and drop from,
    // and the source of the strref list the journal screen shows.
    CExoArrayList<CWorldJournalEntry> m_worldJournal;
    int        m_bLoadFinished;
    char       _pad32c[0x330-0x32c];
    // The limbo list holds objects parked out of any area, as a reverse-scanned id array.
    CExoArrayList<unsigned long long> m_limboList;
    // The save-game plumbing is four heap objects that SaveModuleStart builds and the save steps
    // consume. The destructor does not own them, so a save that never finished leaks them.
    CERFFile*   m_pSaveFile;
    CResStruct* m_pSaveStruct;
    CResGFF*    m_pSaveGFF;
    CExoArrayList<unsigned long long>* m_pSavedObjectIds;
    CExoString m_sTag;
    void SetTag(const CExoString& sTag) { m_sTag = sTag.LowerCase(); }
    // Set when the pending module's resource type is a RIM archive.
    int        m_bIsNWMFile;
    char       _pad374[0x378-0x374];
    CExoString m_sNWMResName;           // the module name, assigned on the same RIM branch
    // The IFO's GFF table count.
    int        m_nTableCount;
    // The cheat dispatcher's byte; no other reader known.
    unsigned char m_nCheatValue;
    char        _pad38d[0x390-0x38d];
    // Only the constructor writes it; nothing reads it.
    int         m_nReserved1;
    char        _pad394[0x398-0x394];
    CSWSAreaMap* m_pAreaMap;
    unsigned long long m_cachedAreaId;  // sentinel means no cached area
    CSWSArea*  m_pCachedArea;

    // The third parameter is never read, but it is part of the constructor's signature, so keep it.
    CSWSModule(const CExoString& name, int bRequest, int nUnused);

    CSWSArea*  GetArea();
    // Runs the module's own half of the alternating update tick, stamping the clock and running the
    // heartbeat script on a six-second cadence, otherwise pushing the new world time out and
    // re-checking the time-stop pause. Returns 1 on the heartbeat tick.
    int        AIUpdate();
    // Drives the module and the current area on alternating ticks.
    void       DoUpdate();
    void       ClearAreaVisitedFlags();
    // Re-checks the server's time-stop exclusion list and unpauses the game when no id on it still
    // carries a time-stop effect.
    void       TimeStopSanityCheck();
    // Debug console hook that parses its argument as a personal-space radius and re-runs the
    // current area's path-point self-test with it.
    void       TestPathPoint(char* pParams);
    void       ClearAreaCache();
    int        GetPrimaryPlayerIndex();
    int        GetPlayerIndexInPlayerList(CSWSPlayer* pPlayer);
    unsigned long long GetWaypoint(const CExoString& tag);
    CExoString GetModuleResourceName();
    int        PlotPath(CPathfindInformation* pPathInfo, unsigned int n);
    // Ensures a route exists, plots within the current area and, on failure, extends the route by
    // one leg and replots (the route layer under PlotPath). The only writer of the path
    // information's transition history.
    unsigned int PlotInterAreaPath(CPathfindInformation* pPathInfo, unsigned int n);
    // The intra-area half, which picks grid or path-point plotting, runs the first-plot direct-line
    // probe and installs the walk path.
    unsigned int PlotPathInArea(CPathfindInformation* pPathInfo, unsigned int n);
    // Turns the head of an inter-area route into an intra-area goal: resolves the first transition id
    // to its trigger or door and rewrites the goal with the closest point inside it.
    void       SetIntraAreaGoal(CPathfindInformation* pPathInfo);
    // The depth-first half of the inter-area route search; returns 1 once the destination area is
    // reached.
    int        InterAreaDFS(int nFrom, int nDepth, CPathfindInformation* pPathInfo);
    // Collects the areas reachable from nFrom in one hop into a newly allocated id array, which the
    // caller frees, and returns its length.
    int        GenerateInterAreaDFSSuccessors(int nFrom, CPathfindInformation* pPathInfo,
                                              unsigned long long** ppaSuccessors);
    // Fills the path information's inter-area route arrays (ten area ids and nine transition ids) by
    // sweeping the depth-first search at increasing depth from the module's own area. Returns 1 with
    // the goal installed when a route was found.
    int        ComputeInterAreaPath(CPathfindInformation* pPathInfo);

    // The limbo list, i.e. objects parked out of any area. A jump to a point pulls a creature back
    // out of it before teleporting.
    int        IsObjectInLimbo(unsigned long long objectId);
    void       AddObjectToLimbo(unsigned long long objectId);
    void       RemoveObjectFromLimbo(unsigned long long objectId);
    // Reaps the ids whose object has since been placed in an area.
    void       CleanUpLimboList();

    // Position of a tag in the sorted table: the index of the first row that does not sort before
    // it, i.e. the row count when it sorts after every row.
    int FindTagPositionInTable(char* sTag);
    // Looks a tag up with an object-type filter, by a binary search over the fixed-size rows, then
    // a scan past its same-tag run for the n-th match of the type.
    unsigned long long FindObjectByTagTypeOrdinal(const CExoString& tag, int nType,
                                                  unsigned int nOrdinal);
    unsigned long long FindObjectByTagOrdinal(const CExoString& tag, unsigned int ordinal);
    bool AddObjectToLookupTable(const CExoString& tag, unsigned long long objectId);
    bool RemoveObjectFromLookupTable(const CExoString& tag, unsigned long long objectId);

    // Module resource remounting, the resource-manager half of a module swap.
    void       RemoveModuleResources(const CExoString& sModule);
    void       AddModuleResources(const CExoString& sModule);
    // Rebuilds the limbo list, and every limbo object's area, from the IFO's own list, which is how an
    // object parked out of any area survives a module save.
    int        LoadLimboCreatures(CResGFF* pGFF, CResStruct* pStruct, int bFromSaveGame);

    // Module save and load state machine.
    void       SaveModuleStart(CExoString& resourceName, CExoString& sFileName);
    // Writes the loaded module's IFO subset into the save's area GFF.
    int        SaveModuleIFOStart(CResGFF* pGFF, CResStruct* pStruct);
    // Writes the faction section, the faction manager's own table, into the open archive.
    int        SaveModuleFAC();
    int        SaveModuleInProgress();
    int        SaveModuleFinish(CExoString& resourceName, CExoString& tag);
    // Dumps the module's non-GFF state into the archive as a plain module-save resource the loader
    // reads back: the resource name, the module tag, the hour and one more integer.
    int        SaveStatic(CERFFile* pERF, const CExoString& sFileType, unsigned short nResType,
                           int nBufferSize);
    // Closes the IFO GFF, stores it into the archive, then hands the object-id list on to the
    // section writers.
    int        SaveModuleIFOFinish(CResGFF* pGFF, CResStruct* pStruct, CERFFile* pERF,
                                   CExoString& sFileName,
                                   CExoArrayList<unsigned long long>& aSavedObjectIds);
    void       SaveLimboCreatures(CResGFF* pGFF, CResStruct* pStruct);
    int        SavePlayers(CResGFF* pGFF, CResStruct* pStruct, const CExoString& sUnused,
                           CExoArrayList<unsigned long long>& aSavedObjectIds);
    unsigned int LoadModuleStart(const CExoString& name, int fromSaveGame);
    unsigned int LoadModuleInProgress(int total, int progress);
    unsigned int LoadModuleFinish();
    // The whole payload of the module-info message.
    void PackModuleIntoMessage(unsigned int nPlayerId);
    // Appends the module's own player list to a character list already built from the servervault
    // directories. Each entry it adds carries the module's own location code, and duplicates are
    // skipped.
    void PackPlayerCharacterListIntoMessage(CSWSPlayer* pPlayer,
                                            CExoArrayList<NWPlayerCharacterList_st*>& list);
    void GetTime(unsigned int* pDate, unsigned int* pHour, unsigned int* pMinute,
                 unsigned int* pSecond, unsigned char* pMs, unsigned int* pUnk);
    void SavePrimaryPlayerInfo(CSWSCreature* pCreature, const CExoString& path);

    // The world journal, the module-wide player-authored log the journal screen shows. Entries are
    // keyed by an index the module hands out and carry a name and text pair plus the world day and
    // time the entry was made.
    int  GetWorldJournalIndexUnique();
    void AddWorldJournalEntry(int nIndex, const CExoString& sName, const CExoString& sText,
                              unsigned int nDay, unsigned int nTime);
    // The strref-keyed add, where the entry's name and text come out of the talk table rather than
    // being carried in the message, so the pair of longs is (name strref, text strref).
    void AddWorldJournalEntryStrref(uint64_t nNameStrRef, uint64_t nTextStrRef,
                                    unsigned int nDay, unsigned int nTime);
    // Pushes a new world time out to the module's listeners. The fan-out is change-gated: only a
    // non-empty diff against what was shipped last reaches the players.
    void UpdateTime(unsigned int nCalendarDay, unsigned int nTimeOfDay, unsigned int nTimeOfDayDelta);
    // Clears the whole world-journal list.
    void DeleteWorldJournalAllEntries();
    void DeleteWorldJournalEntry(int nIndex);
    void DeleteWorldJournalEntryStrref(uint64_t nStrRef);

    // The AI-master event sink. A timed event resumes a suspended script situation, a signal event
    // dispatches its script event sub-type onto the module script block.
    void EventHandler(unsigned int nEventType, unsigned long long nCallerId, void* pData,
                      unsigned int nDay, unsigned int nTod);

    // The loaded-module lifecycle stubs. AsSWSModule is a real vtable slot: it overrides the game
    // object's probe, which is what emits the adjusting thunk for the secondary base.
    void PostProcess();
    void UnloadModule();
};

