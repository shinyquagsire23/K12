// One entry of a character's class list. The level is narrowed to one byte because the GFF field it
// comes from is a short.
struct NWPlayerCharacterListClass_st {
    int           m_nClass;
    unsigned char m_nLevel;
};

// One entry of the multiplayer character-selection list the server ships to a joining client.
struct NWPlayerCharacterList_st {
    // m_nPortraitId when the character has no portraits.2da row.
    enum {
        PORTRAIT_ID_NONE = 0xffff,
    };

    CExoLocString m_firstName;
    CExoLocString m_lastName;

    // Which character store this entry came from: the per-player servervault subdirectory, the flat
    // servervault directory, or the module's own player list.
    unsigned char m_nLocation;

    CResRef        m_resRef;
    unsigned short m_nPortraitId;
    CResRef        m_portrait;
    char           _pad44[4];

    CExoArrayList<NWPlayerCharacterListClass_st> m_classList;

    NWPlayerCharacterList_st()
    {
        m_nLocation = 0;
        m_nPortraitId = PORTRAIT_ID_NONE;
    }

    int operator==(const NWPlayerCharacterList_st& other) const
    {
        return m_firstName == other.m_firstName && m_lastName == other.m_lastName;
    }
};

// The server-side module object is the loaded level, holding its area, the tag to object-id lookup
// table and the module save/load state.
