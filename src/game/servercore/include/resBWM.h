#ifndef CRESBWM_H
#define CRESBWM_H

#include "exoresman.h"
#include "Vector.h"

// The binary walkmesh file header, read in place over the raw file buffer. A door keeps its two
// action points in vecC/vecD; every other type writes zeros there.
struct CResBWMHeader {
    char          magic[8];
    int           meshType;
    Vector        vecA;
    Vector        vecB;
    Vector        vecC;
    Vector        vecD;
    Vector        localOrigin;
    unsigned int  nVertexCount;
    unsigned int  offVertices;
    unsigned int  nTriangleCount;
    unsigned int  offTriVertIndices;
    unsigned int  offTriMaterials;
    unsigned int  offTriNormals;
    unsigned int  offTriPlaneD;
    unsigned int  nAABBNodeCount;
    unsigned int  offAABBNodes;
    unsigned int  nRootAABBIndex;
    unsigned int  nAdjacencyCount;
    unsigned int  offTriAdjacency;
    unsigned int  nEdgeCount;
    unsigned int  offEdgeAdjacency;
    unsigned int  nPerimeterCount;
    unsigned int  offPerimeters;
};

// One node of the room-type box tree, swapped in place by the parser. The in-memory form is
// CSWRoomSurfaceMeshAABBNode, which has the same layout.
struct CResBWMAABBNode {
    Vector corner0;
    Vector corner1;
    int    leafTriangleIndex;
    int    m_nReserved1;
    int    sideMask;
    int    child1;
    int    child2;
};

// The walkmesh (.wok/.dwk/.pwk, binary or text) resource wrapper. Unlike the other walkmesh
// resources this one parses its file, endian-swapping the binary header and every room-type array in
// place and publishing the header over the raw data.
class CResBWM : public CRes {
public:
    CResBWM();
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 6 slots
    virtual ~CResBWM();  // slots 0-1 (D2+D0)
    virtual int OnResourceFreed();
    virtual int OnResourceServiced();
    // </VTABLE-GEN>

    void* GetBWMDataPtr();
    int   GetBWMSize();
    int   IsBinary();

    int            m_bLoaded;
    int            m_nBWMSize;
    void*          m_pBWMData;
#if KOTOR1
    CResBWMHeader  m_header;
#endif
    CResBWMHeader* m_pParsed;
};
#if KOTOR1
K2_LAYOUT_ASSERT(__builtin_offsetof(CResBWM, m_header) == 0x48, "K1 CResBWM layout");
K2_LAYOUT_ASSERT(__builtin_offsetof(CResBWM, m_pParsed) == 0xd0, "K1 CResBWM layout");
K2_LAYOUT_ASSERT(sizeof(CResBWM) == 0xd8, "K1 CResBWM layout");
#endif

#endif
