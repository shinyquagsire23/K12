// A single applied item property: type, subtype, cost table, parameter.
class CSWItemProperty {
public:
    // m_nUpgradeType of a property that belongs to no upgrade slot, and m_nUsesPerDay before the
    // activate-item property's daily uses are read from its cost table.
    enum {
        UPGRADE_TYPE_NONE = 0xff,
        USES_PER_DAY_UNSET = 0xff,
    };

    unsigned short m_type;
    unsigned short m_subType;
    unsigned char  m_nCostTable;
    unsigned char  _pad05[0x06-0x05];
    unsigned short m_costTableValue;
    unsigned char  m_nParam1;
    unsigned char  m_nParam1Value;
    unsigned char  m_nChanceAppear;
    unsigned char  _pad0b[0x0c-0x0b];
    union {
        int            m_bUseable;
        unsigned char  m_bUseableByte;
    };
    unsigned char  m_nUsesPerDay;
    unsigned char  m_nUpgradeType;
    unsigned short m_nPropUpgrade;
    unsigned int   m_nLastUseDay;
    unsigned int   m_nLastUseTod;
};
