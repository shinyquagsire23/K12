#pragma once
#include "k2stdint.h"

// The shared root of the client and server ambient-sound emitters, holding the track selection
// interface and the per-area settings block.
class CSWAmbientSound {
public:
    virtual void PlayMusic(int) = 0;
    virtual void SetMusicDelay(int) = 0;
#if KOTOR1  // K1: the track setters take no streaming flag
    virtual void SetMusicDayTrack(int) = 0;
    virtual void SetMusicNightTrack(int) = 0;
#else
    virtual void SetMusicDayTrack(int, int) = 0;
    virtual void SetMusicNightTrack(int, int) = 0;
#endif
    virtual void PlayBattleMusic(int) = 0;
    virtual void SetBattleMusicTrack(int) = 0;
    virtual void PlayAmbientSound(int) = 0;
    virtual void SetAmbientDayTrack(int) = 0;
    virtual void SetAmbientNightTrack(int) = 0;
    ~CSWAmbientSound() {}

    int  m_bMusicPlaying = 1;
    int  m_nMusicDelay = 5000;
    int  m_nMusicDayTrack = 2;
    int  m_nMusicNightTrack = 3;
    int  m_bBattleMusicPlaying = 0;
    int  m_nBattleMusicTrack = 1;
    int  m_bAmbientPlaying = 1;
    int  m_nAmbientDayTrack = 1;
    int  m_nAmbientNightTrack = 2;
    unsigned char m_nAmbientDayVolume = 0;
    unsigned char m_nAmbientNightVolume = 0;
};

// The client-side ambient-sound emitter, one instance per area, owned by CSWCArea::m_pAmbientSound.
// It keeps its live music delay in m_nMusicDelay.
#include "exostring.h"

class CSWCArea;
class CSWCMessage;
class CExoStreamingSoundSource;

// A track descriptor, read out of the 2DA row one of the streaming tables names.
struct CSWCAmbientSoundTrack {
    CExoString m_sResource;
    CExoString m_sStinger1;
    CExoString m_sStinger2;
    CExoString m_sStinger3;
};

// Playback priorities are ordered because PlayTruncated will not interrupt a channel already
// playing at a higher priority.
enum CSWCAmbientSoundPriority {
    SOUND_PRIORITY_NONE = 0,
    SOUND_PRIORITY_MUSIC = 1,
    SOUND_PRIORITY_AMBIENT = 2,
    SOUND_PRIORITY_BATTLE = 4,
};

