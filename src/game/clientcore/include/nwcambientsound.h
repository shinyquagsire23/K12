#if KOTOR1  // K1 takes the track alone; K2 adds a second argument
    virtual void SetMusicDayTrack(int nTrack);
    virtual void SetMusicNightTrack(int nTrack);
#else
    virtual void SetMusicDayTrack(int, int);
    virtual void SetMusicNightTrack(int, int);
#endif
    virtual void PlayBattleMusic(int);
    virtual void SetBattleMusicTrack(int);
    virtual void PlayAmbientSound(int);
