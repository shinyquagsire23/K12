// One item cell in CSWGuiStore's buy and sell lists, a button carrying a 36-pixel,
// resolution-scaled icon frame, a second CSWGuiText for the stack count, and the item's object id.
//
// The frame pair is the slot background, the inactive arm drawing the normal frame and the active arm
// the hilight, and the third border carries the item icon. SetItem installs the UIBIT_EQP_ITM1/2/3
// stack-size frame on the pair and CSWSItem::GetIcon's resref on the icon border, and builds the count
// caption with CExoString::Format("%d", pItem->m_stackCount); SetExtent picks a 55- or 21-pixel line
// height from that string's length.


class CSWGuiBorderParams;
struct CSWGuiExtent;
class CSWGuiTextParams;
class CExoString;

class CSWGuiStoreItemEntry : public CSWGuiButton {
public:
    CSWGuiStoreItemEntry();

    virtual void SetExtent(const CSWGuiExtent& extent);
    virtual void Draw(float f);
    virtual void Initialize(CSWGuiExtent const&, CSWGuiTextParams const&, CSWGuiBorderParams const&, CSWGuiBorderParams const&);  // empty
    virtual void Initialize(CSWGuiExtent const&, CSWGuiButton*);  // empty
    virtual void Initialize(CSWGuiText&, CSWGuiBorder&, CSWGuiBorder&, int);

    void SetColors(Vector colorFrame, Vector colorText, Vector colorHilight, Vector colorUnused);
#if KOTOR1
    void SetItem(unsigned long long oidItem, int bIsEquipped);  // no equipped-slot argument in K1
#else
    void SetItem(unsigned long long oidItem, int bIsEquipped, int nEquippedBy);
#endif

    // CSWGuiButton's own fields end here.

    unsigned long long m_oidItem;       // ctor default OBJECT_INVALID
    CSWGuiBorder m_borderFrame;         // drawn when !m_tail.bActive
    CSWGuiBorder m_borderFrameHilight;  // drawn when  m_tail.bActive
    CSWGuiBorder m_borderIcon;          // always drawn; carries the item icon resref
    CSWGuiText   m_textCount;           // the "%d" stack count
#if !KOTOR1  // K1's row ends at the count caption
    int          m_nEquippedBy;            // == -1 suppresses the " (...)" name suffix
    int          m_nCreateRow;            // ctor default -1
    int          m_bCanCreate;            // ctor default 0
#endif
};

