class CSWGuiStatusSummary : public CSWGuiPanel {
public:
    // Only the three overrides below are declared; HandleInputEvent is the key function, so the
    // destructor stays implicit.
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 30 slots
    virtual void HandleInputEvent(int type, int val);
    virtual void OnPanelAdded();
    virtual void OnPanelRemoved();
    // </VTABLE-GEN>
    CSWGuiStatusSummary(CSWGuiManager* pGuiManager);
    void Clear();
    void AddCredits(int credits);
    void AddAlignmentShift(char shift);
    // K1 has none of the next six; the four Add* stay declared for CGuiInGame::UpdateStatus.
    void AddInfluenceGained(char nMemberId);
    void AddInfluenceLost(char nMemberId);
    void AddMaxFPGained(int nAmount);
    void AddMaxFPLost(int nAmount);
#if !KOTOR1
    void HandleAlignmentMovie();
    void HandleLevelUpDLG();
#endif
    void DisplayStatus();
    void PlayPendingSounds();

    // m_flags' bits, in CStatusSummary's bit-field order. KOTOR 1 has no alignment sounds and
    // keeps CREDITSNET at bit 8.
    enum {
        SUMMARY_DISPLAY_PENDING = 0x1,
        SUMMARY_SOUND_PENDING = 0x2,
        SUMMARY_ITEM_RECEIVED = 0x4,
        SUMMARY_ITEM_LOST = 0x8,
        SUMMARY_JOURNAL = 0x10,
        SUMMARY_LEVEL_UP_SOUND = 0x20,
        SUMMARY_NEW_QUEST_SOUND = 0x40,
        SUMMARY_COMPLETE_SOUND = 0x80,
#if KOTOR1
        SUMMARY_CREDITS_NET = 0x100,
        SUMMARY_ALL = 0x1ff,
#else
        SUMMARY_DARK_ALIGN_SOUND = 0x100,
        SUMMARY_LIGHT_ALIGN_SOUND = 0x200,
        SUMMARY_CREDITS_NET = 0x400,
        SUMMARY_ALL = 0x7ff,
#endif
    };

    // The rows, m_aValueLabels' and m_aDescLabels' index (LBL_JOURNAL to LBL_MAX_FP_LOST).
    enum SummaryRow {
        SUMMARY_ROW_JOURNAL = 0,
        SUMMARY_ROW_CREDITS = 1,
        SUMMARY_ROW_XP = 2,
        SUMMARY_ROW_STEALTH_XP = 3,
        SUMMARY_ROW_DARK_SIDE = 4,
        SUMMARY_ROW_LIGHT_SIDE = 5,
        SUMMARY_ROW_NET_SHIFT = 6,
        SUMMARY_ROW_ITEM_RECEIVED = 7,
        SUMMARY_ROW_ITEM_LOST = 8,
#if !KOTOR1
        SUMMARY_ROW_INFLUENCE_GAINED = 9,
        SUMMARY_ROW_INFLUENCE_LOST = 10,
        SUMMARY_ROW_MAX_FP_GAINED = 11,
        SUMMARY_ROW_MAX_FP_LOST = 12,
#endif
    };

    // The summary itself, field for field as CStatusSummary lays it out (Get/SetSummary copy it
    // whole): the panel reads the flag bits as one word and the two shifts as bytes.
#if KOTOR1  // K1's summary holds nine flag bits, CREDITSNET included
    alignas(CStatusSummary) unsigned short m_flags;
    unsigned char  m_lightShift;
    unsigned char  m_darkShift;
    int            m_credits;
    int            m_nXP;
    int            m_nStealthXP;
    int            m_suppressFlag;
#else
    alignas(CStatusSummary) unsigned short m_flags;  // the 11 pending bits, 0 to 10, bit 0 being
                                                     // DISPLAYSPENDING
    unsigned char  m_lightShift;  // the GFF's light-shift and dark-shift bytes
    unsigned char  m_darkShift;
    int            m_credits;
    int            m_nXP;         // "XP", fed by CSWSDialog's quest and experience awards
    int            m_nStealthXP;  // "STEALTHXP", fed by CSWSArea's m_currentStealthXP
    int            m_suppressFlag;  // set by CGuiInGame::SuppressStatusSummary; UpdateStatus
                                    // decrements while positive instead of processing
    int            m_influenceGainedMask;  // bit N set == member N gained influence
    int            m_influenceLostMask;  // bit N set == member N lost influence
    int            m_maxFPGained;
    int            m_maxFPLost;
#endif
    void SetSummary(const CStatusSummary& summary) { __builtin_memcpy(&m_flags, &summary, sizeof(CStatusSummary)); }
    void GetSummary(CStatusSummary& summary) const { __builtin_memcpy(&summary, &m_flags, sizeof(CStatusSummary)); }
    unsigned char m_bTogglePauseAtEndOfFrame;  // bit 0 is ShowStatusSummary's cached copy of
                                               // GetTogglePauseAtEndOfFrame, forced true while
                                               // CGuiInGame::m_bPaused is set; bits 1-7 preserved
#if KOTOR1  // K1's labels start earlier
    char _pad91[7];
#else
    char _padcd[0xd0-0xcd];
    int m_nAlignmentChanged;
    char _padd4[0xd8-0xd4];
#endif
    CSWGuiLabel  m_lblReserved1;  // layout-only, never InitControl'd
    CSWGuiLabel  m_lblReserved2;  // layout-only, never InitControl'd
#if KOTOR1  // K1 has nine rows, JOURNAL through LOST
    CSWGuiLabel  m_aValueLabels[9];
    CSWGuiLabel  m_aDescLabels[9];
#else
    CSWGuiLabel  m_aValueLabels[13];  // LBL_JOURNAL to LBL_MAX_FP_LOST
    CSWGuiLabel  m_aDescLabels[13];  // LBL_JOURNAL_DESC to LBL_MAX_FP_LOST_DESC
#endif
    CSWGuiButton m_btnAck;
};

