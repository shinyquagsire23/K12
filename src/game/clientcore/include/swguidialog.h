// Defined here so the derived classes share the body.
inline void CSWGuiDialog::SetDialogMessage(const CExoString& msg)
{
    m_listBox.m_tail.bVisible = 0;
    m_msgLabel.m_tail.bVisible = 0;
    m_sDialogMessage = msg;

    // In the autopause gate, a message that belongs to the in-game camera keeps the dialog visible.
    if ((m_nMessageFlags & DIALOGMSG_DIALOG_ENDED) != 0
        && g_pAppManager->m_pClientExoApp->GetInGameGui()->IsCameraDialog())
    {
        m_nMessageFlags = static_cast<unsigned char>(
            (m_nMessageFlags & ~(DIALOGMSG_LINE_PENDING | DIALOGMSG_DIALOG_ENDED)) | DIALOGMSG_LINE_PENDING);
    }
    else
    {
        ShowDialogMessage();
    }

    m_nMessageFlags |= DIALOGMSG_SHOWING_LINE;
}

