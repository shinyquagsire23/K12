// One qualifying flat attack/damage-bonus record, the element type of both of CCombatInformation's
// lists. Partial model: only the fields the two bonus-string filters touch are named, under the
// engine's own GFF labels from SaveData/LoadData.
class CCombatInformationNode {
public:
    signed char   m_cValue;      // "Modifier": flat delta added to the attack bonus when the record
                                 // qualifies
    unsigned char m_nModifierType; // "ModifierType": per-record descriptor sub-type, 0-14
    unsigned char m_nType;       // "WeaponWield": the attack-bonus filter admits 1, 2, 6 and 7, and
                                 // admits 7 only when nothing is equipped in the on-hand slot
    unsigned char m_nFlag;       // "VersusGoodEvil": must be 0 for the record to qualify; the
                                 // damage-bonus string also switches on it for an extra descriptor
    // Declared but not defined: default construction goes through it.
    CCombatInformationNode();

    unsigned char m_nClassReq;   // "VersusRace": when it differs from g_pRules->m_nNumRaces, the
                                  // damage-bonus string appends the matching suffix from
                                  // g_pRules->m_paRaces

    // Defined out of line in CCombatInformation's home translation unit;
    // CCombatInformation's assignment and inequality operators are built on them.
    int operator==(CCombatInformationNode& other);
    int operator!=(CCombatInformationNode& other);
    CCombatInformationNode& operator=(const CCombatInformationNode& other);
};

// Per-creature combat summary: attack counts, force resistance, arcane spell failure and two
// owned node lists.
class CCombatInformation {
public:
    unsigned char m_nNumOnHandAttacks;
    signed char   m_nAttackModOnHand;    // strength ability modifier
    signed char   m_nStrDamageModOnHand; // the same modifier, on the damage bonus
    signed char   m_nAttackModOffHand;   // the off-hand equivalents, populated server-side
    signed char   m_nStrDamageModOffHand;
    unsigned char m_nForceResistance;
    unsigned char m_nArcaneSpellFailure;
    unsigned char m_bArmorCheckPenalty;  // nonzero selects the penalty string
    unsigned char m_nDefaultDamageDie;   // fallback damage die when no item is looked up
    unsigned char m_nDefaultDamageDiceCount; // fallback dice count for the same case
    unsigned char m_nCritRangeOnHand;      // 0 or 1 means a threat range of 20 only
    unsigned char m_nCritMultiplierOnHand; // the "x%d" multiplier
    int           m_bOffHandWeaponEquipped;             // off-hand attack flag: 1 means one off-hand attack
    unsigned char m_nCritRangeOffHand;
    unsigned char m_nCritMultiplierOffHand;
    // Both lists are walked by count and also indexed by hand number: the first two entries double
    // as fixed per-hand records.
    CExoArrayList<CCombatInformationNode*> m_attackBonusMods;  // "AttackList"
    CExoArrayList<CCombatInformationNode*> m_damageBonusMods;  // "DamageList"
    // Equipped weapon ids and display names, filled by SaveStats. The on-hand item's baseitems.2da
    // DieToRoll/NumDice feed the override fields below.
    unsigned long long m_onHandWeaponId;
    unsigned long long m_offHandWeaponId;
    CExoString    m_onHandWeaponName;
    CExoString    m_offHandWeaponName;
    // Overrides for a natural or special weapon, used instead of the equipped item's baseitems.2da
    // row. A nonzero dice count both enables the override and supplies the count; both hands share
    // it.
    unsigned char m_nOverrideDie;
    unsigned char m_nOverrideNumDice;

    CCombatInformation();
    ~CCombatInformation();
    // Field-by-field equality. The inequality form decides whether the client's cached combat
    // information is stale.
    int operator==(CCombatInformation& other);
    int operator!=(CCombatInformation& other);
    // Deep copy: self-check, field copy, clear both node lists, then a fresh node per source
    // element.
    CCombatInformation& operator=(CCombatInformation& other);
    // 1 on success.
    int SaveData(CResGFF* pGFF, CResStruct* pStruct);
    int LoadData(CResGFF* pGFF, CResStruct* pStruct);
};

