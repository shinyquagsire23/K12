// One row of feat.2da; the field names are the table's own column strings.
class CSWFeat {
public:
    // m_nFlags bits.
    enum {
        FLAG_GAIN_MULTIPLE       = 0x01,
        FLAG_ALL_CLASSES_CAN_USE = 0x02,
        FLAG_TARGET_SELF         = 0x04,
        FLAG_HOSTILE             = 0x08,
        FLAG_PRESENT             = 0x10,   // the row exists in feat.2da
        FLAG_MASK                = 0x1f,
    };

    CSWFeat();
    // Empty but user-provided, so `new CSWFeat[n]` keeps the array cookie its delete relies on.
    ~CSWFeat();

    void SetIcon(CResRef resIcon) { m_icon = resIcon; }

    int         m_nSuccessor;         // next feat in the upgrade chain, -1 when the chain ends
    int         m_nSpellId;
    int         m_nNameStrRef;
    int         m_nDescriptionStrRef;
    int         m_nCategory;
    int         m_nMaxCR;
    CResRef     m_icon;
    // Bit 0 "GainMultiple", 1 "AllClassesCanUse", 2 "TargetSelf", 3 "HostileFeat", 4 row is
    // present in feat.2da (set by default, cleared when the "Feat" column lookup fails; GetFeat
    // and IsFeatUseable both gate on it). Bits 5-7 are never written.
    unsigned char m_nFlags;
    unsigned char m_nMinAttackBonus;
    unsigned char m_nMinCharLevel;
    unsigned char m_nMinSTR;
    unsigned char m_nMinDEX;
    unsigned char m_nMinINT;
    unsigned char m_nMinWIS;
    unsigned char m_nMinSpellLvl;
    unsigned char m_maxUses;          // per-day use cap
    char          m_nMasterFeat;      // "MASTERFEAT", -1 when the row has no master feat
    unsigned char _pad32[0x34 - 0x32];
    unsigned short m_nPrereqFeat1;    // 65535 = no prerequisite
    unsigned short m_nPrereqFeat2;    // 65535 = no prerequisite
    unsigned short m_anOrReqFeat[5];  // "OrReqFeat1".."OrReqFeat5", any one satisfies; 65535 = none
    short         m_nReqSkill;        // "REQSKILL"
#if !KOTOR1
    // Per-companion auto-grant gates: a feat goes to the companion whose tag matches when the
    // byte equals the party's total character level. -1 excludes the feat from the ordinary
    // class-granted path.
    unsigned char m_nHandmaidenGrantLevel; // "HANDMAIDEN"
    unsigned char m_nBaodurGrantLevel;   // "BAODUR"
    unsigned char m_nHanharrGrantLevel;  // "HANHARR"
    unsigned char m_nHK47GrantLevel;     // "HK47"
    unsigned char m_nG0T0GrantLevel;     // "G0T0"
    unsigned char m_nAttonGrantLevel;    // "ATTON"
    unsigned char m_nKreiaGrantLevel;    // "KREIA"
    unsigned char _pad4b[0x4c - 0x4b];
#endif

    CExoString GetNameText();
    CExoString GetDescriptionText();
};

class CSWRules {
public:
    // Declared but not defined; callers construct the rules through it.
    CSWRules();
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 2 slots
    virtual ~CSWRules();  // slots 0-1 (D2+D0)
    // </VTABLE-GEN>

    // Spell ranges by spells.2da "Range" letter, filled from Ranges.2da rows 0-4 and 19. The
    // readers index with the letters themselves, so P and T are separate slots here, unlike the
    // minimum table below.
    float          m_fSpellRange[6];    // [0]="P" [1]="T" [2]="S" [3]="M" [4]="L" [5]="W"
    // Minimum ranges, filled in the same loop. The readers map P onto the T entry, leaving element 0
    // unused.
    float          m_fMinSpellRange[6]; // [0]="P"(unused) [1]="T"/"P" [2]="S" [3]="M" [4]="L" [5]="W"
    // baseitems.2da, read for the "PT_COST_MULT_LIST" per-item cost multipliers.
    CSWBaseItemArray* m_pBaseItemArray;
#if KOTOR1
    int            m_aExpTable[21];  // exptable.2da "EXPTABLE"; K1 caps levels at 20
#else
    int            m_aExpTable[51];  // exptable.2da "EXPTABLE": XP required per level, entries 0-50
#endif
    CSWSpellArray* m_pSpellArray;
    CSWFeat*       m_paFeats;      // one entry per feat.2da row
    // Three parallel master-feat arrays; each is its own allocation with its own getter.
    int*     m_paMasterFeatNameStrRefs;
    int*     m_paMasterFeatDescriptionStrRefs;
    CResRef* m_paMasterFeatIcons;
    short*   m_paFeatIndices;      // the feat.2da row indices that exist, length m_nFeatIndices
    unsigned short m_nFeats;       // feat.2da row count, the bound GetFeat checks
    unsigned short m_nFeatIndices;
    char           m_nNumMasterFeats;  // MasterFeats.2da row count
    unsigned char  m_nNumClasses;         // class-count bound in ReadStatsFromGff's "Class" range check
    // racialtypes.2da row count: the scripting RACIAL_TYPE_ALL sentinel, with RACIAL_TYPE_INVALID
    // one past it. Effects encode "applies to any race" as this value.
    unsigned char  m_nNumRaces;
    unsigned char  m_nNumSkills;   // skill.2da row count, the bound in GetSkillRank/ClearSkills
    CSWClass*      m_paClasses;    // class.2da entries; one field gates GetCasterLevel
    CSWRace*       m_paRaces;      // racialtypes.2da entries, indexed by CSWCCreatureStats::m_nRace
    CSWSkill*      m_paSkills;     // skill.2da entries, each carrying its key ability index
    CTwoDimArrays* m_p2DArrays;    // every gameplay 2DA table
    // DiffSettings.2da, indexed [difficulty level][option].
    unsigned char  m_difficultyOptions[5][6];

    void    LoadFeatInfo();
    void    LoadSkillInfo();
    void    LoadClassInfo();
    void    LoadRaceInfo();
    void    LoadDifficultyInfo();
    CSWFeat* GetFeat(unsigned short nFeat);
    CSWSpell* GetSpell(unsigned int nSpellId) { return m_pSpellArray->GetSpell(nSpellId); }
    CSWBaseItem* GetBaseItem(unsigned int nBaseItem) { return m_pBaseItemArray->GetBaseItem(nBaseItem); }
    int     IsFeatUseable(unsigned char nWisdom, unsigned short nFeat);
    CExoString GetMasterFeatNameText(char nMasterFeat);
    CExoString GetMasterFeatDescriptionText(char nMasterFeat);
    CResRef GetMasterFeatIcon(char nMasterFeat);
    unsigned short RollDice(unsigned char nDice, unsigned char nSides);
    int     GetMetaMagicLevelCost(unsigned char nMetaMagic);

    int GetDifficultyOption(int nOption, int nDifficulty);
    int GetWeightedDamageAmount(int nBase, int nMax, int nFlagA, int nFlagB, int nPercent);
};

