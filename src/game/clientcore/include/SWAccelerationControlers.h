#pragma once

// Runge-Kutta integration state for an accelerating value (swoop or vehicle speed).

#include "Vector.h"

// The state a solver integrates, a velocity and a second, unused vector.
struct CSWPhysicsState {
    Vector m_vValue;
    Vector m_vDisplacement;

    CSWPhysicsState() : m_vValue(), m_vDisplacement() {}
    CSWPhysicsState(const Vector& vValue, const Vector& vDisplacement)
        : m_vValue(vValue), m_vDisplacement(vDisplacement) {}

    CSWPhysicsState& operator+=(const CSWPhysicsState& s)
    {
        m_vValue = m_vValue + s.m_vValue;
        m_vDisplacement = m_vDisplacement + s.m_vDisplacement;
        return *this;
    }
};

inline CSWPhysicsState operator+(const CSWPhysicsState& a, const CSWPhysicsState& b)
{
    return CSWPhysicsState(a.m_vValue + b.m_vValue, a.m_vDisplacement + b.m_vDisplacement);
}

inline CSWPhysicsState operator*(const CSWPhysicsState& s, float f)
{
    return CSWPhysicsState(s.m_vValue * f, s.m_vDisplacement * f);
}

// A zero divisor returns the zero state.
inline CSWPhysicsState operator/(const CSWPhysicsState& s, float f)
{
    if (f != 0.0f)
        return CSWPhysicsState(s.m_vValue / f, s.m_vDisplacement / f);
    return CSWPhysicsState();
}

class CSWRK4Acceleration {
public:
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 1 slots
    // Returns a Vector by value, not void: every call site in Accelerate reads the result back and
    // scales it by the timestep. Pinned inside the block so a header regeneration will not revert
    // it to void.
    virtual Vector GetAccelerationVector(CSWPhysicsState& state, Vector const& vVelocity);
    // </VTABLE-GEN>

    Vector          m_velocity;
    CSWPhysicsState m_prev;
    CSWPhysicsState m_cur;
    float           m_fMaxSpeed;
    float           m_fAcceleration;

    CSWRK4Acceleration();
    CSWRK4Acceleration(float a, float b);

    void Accelerate(Vector const& vVelocity, float fDeltaTime);
    void SetVelocity(float velocity);
    // Resets the four state slots the int arguments select and returns the integrated state.
    CSWPhysicsState Update(Vector vVelocity, float fDeltaTime, int a, int b, int c, int d);
};

