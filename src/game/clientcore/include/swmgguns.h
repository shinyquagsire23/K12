// The minigame gun banks and the two parameter blocks they pass around.

#pragma once

#include "exoresman.h"

// The per-gun bullet description says what to spawn, how fast, how long it lives and what it may
// hit.
struct CSWMGBullet {
    int     m_nDamage;
    float   m_fSpeed;
    float   m_fRateOfFire;
    float   m_fLifeSpan;
    int     m_nTargetType;
    char    _pad14[0x18 - 0x14];
    CResRef m_resModel;

    CSWMGBullet();
};

// The auto-aim tunables, shared by CSWMGTargettingGunBank and CSWMGBehaviorTrack.
struct CSWMGTargettingParameters {
    float m_fHorizontalSpread;
    float m_fSensingRadius;
    float m_fVerticalSpread;
    float m_fInaccuracy;

    CSWMGTargettingParameters();
};

#include "CExoArrayListDtors.h"
#include "exoresman.h"

class CAurObject;
class CAurPart;
class CSWTrackFollower;

// One firing emplacement of the swoop/turret minigame, owned by a CSWTrackFollower: the gun
// models, the bullet prototype and the ballistics tunables.
class CSWMGGunBank {
public:
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 3 slots
    virtual CAurObject* AddGun(CAurObject*, CAurPart*);  // returns the new gun, null on every early-out
    virtual void Die();
    virtual int  IsTargetting();  // int rather than bool; callers test the whole word
    // </VTABLE-GEN>
    CResRef     m_resBullet;
    CResRef     m_resGunModel;
    CResRef     m_resFireSound;
    CExoArrayList<CAurObject*> m_aGuns;
    CSWMGBullet m_bullet;
    CSWTrackFollower* m_pTrackFollower;

    ~CSWMGGunBank();

    // These setters return the stored field. An out-of-range value is rejected, otherwise it is
    // stored and returned.
    float SetBulletSpeed(float speed);
    float SetBulletLifeSpan(float lifespan);
    CAurObject* GetGun(int index);
    CAurObject* RemoveGun(CAurObject* pGun);
    void        Fire();
    int         ClearGuns();
    void        Hit();
    float       SetRateOfFire(float rate);
    int         SetBulletTargetType(int nType);
    CSWMGGunBank(CSWTrackFollower* pTrackFollower, const CResRef& resBullet,
                 const CResRef& resGun, const CSWMGBullet& bullet);
    void        OnFire();
    void        SetGunModel(const CResRef& res);
    void        SetBulletModel(const CResRef& res);
    void        SetFireSound(const CResRef& res);
};

inline void CSWMGGunBank::SetBulletModel(const CResRef& res)
{
    m_resBullet = res;
}

inline void CSWMGGunBank::SetFireSound(const CResRef& res)
{
    m_resFireSound = res;
}

// A gun bank with auto-aim on top, adding a targetting parameter block and the vehicle it aims at.
class CSWMGTargettingGunBank : public CSWMGGunBank {
public:
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 3 slots
    virtual CAurObject* AddGun(CAurObject*, CAurPart*);  // returns the new gun, null on every early-out
    virtual void Die();
    virtual int  IsTargetting();  // int, matching the base
    // </VTABLE-GEN>
    CSWMGTargettingParameters m_targetting;
    CSWTrackFollower* m_pTarget;

    // -1 is a sentinel meaning "no explicit spread", so the spread setters accept it even though
    // it fails the non-negative gate; the radius and inaccuracy setters accept only >= 0.
    CSWMGTargettingGunBank(CSWTrackFollower* pTrackFollower, const CResRef& resBullet,
                           const CResRef& resGun, const CSWMGBullet& bullet,
                           const CSWMGTargettingParameters& params,
                           CSWTrackFollower* pTarget);
    float SetSensingRadius(float radius);
    float SetHorizontalSpread(float spread);
    float SetVerticalSpread(float spread);
    float SetInaccuracy(float inaccuracy);
};
