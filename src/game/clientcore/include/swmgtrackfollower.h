// The player-controlled vehicle, a swoop bike or a turret.
class CSWMiniPlayer : public CSWTrackFollower {
public:
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 17 slots: slots 0-5 and 9 are CSWTrackFollower's, 7/8 CSWMiniGameObject's
    //   and 14 CSWTrackFollower::AddModel's; this class replaces only the six below.
    virtual CSWMiniGameObject* AsPlayer() { return this; }  // returns this; the base returns null
    virtual ~CSWMiniPlayer();
    virtual int Load(CResGFF*, CResStruct*);  // returns 1
    virtual int LoadGun(CResGFF*, CResStruct*);  // returns 1 on success, 0 on failure
    virtual void SetLooping(int loop);  // writes the base's m_numLoops
    virtual int TargetType() { return 1; }  // player minigame-object type (the enemy's is 2)
    // </VTABLE-GEN>

    CExoArrayList<SWMGKeyInfo>  m_keyInfo;
    CExoArrayList<SWMGKeyInfo>  m_keyInfo2;
    CExoArrayList<SWMGKeyInfo*> m_paKeyInfo;

    Vector m_vOffset;
    int   m_nBank;
    unsigned char m_bBumped;
    char  _pad249[0x24c-0x249];
    float m_minSpeed;
    float m_maxSpeed;
    float m_aps;
    Vector m_vTunnelPos;
    Vector m_vTunnelNeg;
    Vector m_vTunnelInfinite;
    Vector m_vOrigin;
    Vector m_vTargetOffset;
    CAurObject* m_pCameraHook;
    unsigned char m_bCameraHook;
    char  _pad2a1[0x2a4-0x2a1];
    Vector m_vLastVelocity;
    Vector m_vStartHookPosition;
#if KOTOR1  // K1 stores a whole quaternion here, written by Control
    Quaternion m_qStartHookOrientation;
#else
    float  m_fStartHookOrientationW;
    unsigned long long m_nStartHookOrientationXY;
    int    m_nStartHookOrientationZ;
#endif

    CSWMiniPlayer(CSWMiniGame* pMiniGame);

    void SetCameraHook(CAurObject* pModel, unsigned char bHook);

    Vector SetOffset(const Vector& v);
    Vector SetOrigin(const Vector& v);
#if KOTOR1  // K1 returns the kept value, like SetMaxSpeed
    float SetMinSpeed(float speed);
    float SetAPS(float aps);
#else
    void SetMinSpeed(float speed);
    void SetAPS(float aps);
#endif
    float SetMaxSpeed(float speed);
    void Fire();
    CSWMGGunBank* CreateGunBank(int nBankId, const CResRef& resBulletModel,
                                 const CResRef& resGunModel, const CSWMGBullet& bullet,
                                 const CResRef& resFireSound);
    void Control(float fDelta, CSWMGPhysicsState& cur, CSWMGPhysicsState& prev);
    void KeepInTunnel(Vector& vOffset);
    // Computes the inertia force in the vehicle's own frame from the two positions whose difference
    // over fDelta is the new velocity. Nothing in the shipped engine calls it.
    Vector DoInertia(const Vector& vFrom, const Vector& vTo, const Quaternion& qRot, float fDelta);
    // Vehicle-versus-vehicle collision pass over the given object ids: the list is swept backwards
    // and compacted in place, and bApply gates every side effect. Returns the hit count. Nothing in
    // the shipped engine calls it.
    int DoFollowerHitCheck(CExoArrayList<unsigned int>& list, int bApply);
    // Replays the bank animation for the signed bank index nAmount, clamped to +-10. With bAdd
    // zero the cached bank is set and an unchanged index returns early; non-zero accumulates.
    void AdjustPosition(int nAmount, int bAdd);
};
