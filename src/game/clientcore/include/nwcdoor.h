// Client-side door object. Only the door's own fields are modelled here.

#include "nwcobject.h"
#include "serveranimation.h"

class CSWCCreature;
class CSWSDoor;
template <class T> class CExoArrayList;
class CSWGuiInterfaceAction;

class CExoString;
class CResRef;
class CSWCDoor;

class CSWCDoor : public CSWCObject {
public:
    // GetState / SetState: the door's resting state, set from the animation it last finished.
    enum {
        DOOR_STATE_CLOSED    = 0,
        DOOR_STATE_OPEN1     = 1,
        DOOR_STATE_OPEN2     = 2,
        DOOR_STATE_DESTROYED = 3,
    };

    // m_nAppearance and m_nGenericType before the door's template has set them.
    enum {
        APPEARANCE_NONE = 0xff,
    };

    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 83 slots
    CSWCDoor();

    virtual ~CSWCDoor();  // slots 0-1 (D2+D0)
    virtual CSWCDoor* AsSWCDoor();
    virtual CExoString GetName();
    virtual void AIUpdate();
    virtual int LoadModel(const CResRef& r, unsigned char a, unsigned char b);
    virtual void UnloadModel();
    virtual void UnloadModel(unsigned char a);
    // </VTABLE-GEN>
    CExoString    m_name;
    int           m_bPlot;
#if !KOTOR1  // K1 has no door mines, so the fields from here to 0x17d sit four bytes lower
    int           m_bNotBlastable;
#endif
    int           m_bLocked;
    int           m_bLockable;
    int           m_bHilighted;
    int           m_bHostileFaction;
    int           m_nDestroyedAnimVariant;
    unsigned char m_state;
    char          _pad175[0x178-0x175];
    int           m_bHilightShown;
    unsigned char m_nAppearance;
    unsigned char m_nGenericType;
#if KOTOR1
    char          _pad17a[0x180-0x17a];
#else
    char          _pad17e[0x180-0x17e];
#endif
    int           m_nReserved1;
    int           m_nReserved2;
    int           m_isAreaTransition;
    char          _pad18c[0x190-0x18c];
    CExoString    m_sModelName;
    int           m_bStatic;
    char          _pad1a4[0x1a8-0x1a4];
    CExoString    m_transitionDestination;

    CSWSDoor*     GetServerDoor();
    unsigned char GetState();
    // Whether the door is playing one of its two opened animations.
    int           GetIsOpen()
    {
        return GetCurrentAnimation() == SERVER_ANIMATION_DOOR_OPEN1 ||
               GetCurrentAnimation() == SERVER_ANIMATION_DOOR_OPEN2;
    }
    void          SetState(unsigned char state);
    void          SetIsAreaTransition(int b);
    void          UpdateAreaTransitionDisplay();
    void          AnimationUpdate();
    void          SetAnimationWithoutTrigger(unsigned short anim);
    void          ToggleLockState();
    void          HilightDoor(int a);
    void          SetMineIcon(unsigned char a);
    void          AddFireAndForgetAnimation(unsigned short a, void* p, unsigned short b);
    void          ActionMenuExamine(unsigned int a, CSWCCreature* pCreature);
    void          MenuActionSecurity(unsigned int a, CSWCCreature* pCreature);
    void          MenuActionBash(unsigned int a, CSWCCreature* pCreature);
    void          MenuActionSetDoorMine(unsigned int a, CSWCCreature* pCreature);
    void          ToggleDoorState(unsigned int a, CSWCCreature* pCreature);
    void          DoorSaber(unsigned int a, CSWCCreature* pCreature);
    void          GetTargetActions(CSWCCreature* pCreature, int nType,
                                   CExoArrayList<CSWGuiInterfaceAction>& list);
    void          GetUseItems(CSWCCreature* pCreature,
                             CExoArrayList<CSWGuiInterfaceAction>& list);
#if !KOTOR1
    void          GetDoorInterfaceMines(CSWCCreature* pCreature,
                                        CExoArrayList<CSWGuiInterfaceAction>& list);
#endif

};
