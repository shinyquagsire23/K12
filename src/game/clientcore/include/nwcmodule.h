// Camera state saved for restore. m_pTarget's SafePointer makes the record non-trivially
// destructible, since it un-registers from the target's watcher list.
class CCameraSettings {
public:
    int    m_bValid;
    int    m_nCameraType;             // CAMERA_ON_STICK or CAMERA_FREE_LOOK
    CAurObject* m_pCameraObject;
    SafePointer<CAurObject> m_pTarget;
    int    m_nStyle;
    int    m_nFollowingBody;
    float  m_fTargetHeight;
    int    m_nVideoEffect;
#if !KOTOR1
    float  m_fTilt;
#endif
    static const int CAMERA_ON_STICK;
    static const int CAMERA_FREE_LOOK;
};

// Client-side module object: owns the camera stack and the loaded client area.
class CSWCModule : public CGameObject {
public:
    // m_nLastCameraMode before the first camera update has recorded one.
    enum {
        LAST_CAMERA_MODE_NONE = 0xff,
    };

    // m_nTimeOfDayState; NONE until the server first sends one.
    enum {
        TIME_OF_DAY_NONE  = 0,
        TIME_OF_DAY_DAY   = 1,
        TIME_OF_DAY_NIGHT = 2,
        TIME_OF_DAY_DAWN  = 3,
        TIME_OF_DAY_DUSK  = 4,
    };

    int          m_nCameraMode;
    CExoString   m_sModuleDisplayName;
    CResRef      m_cModuleHak;
    CResRef      m_cStartMovie;
    CExoString   m_sModuleName;
    CAurCamera*  m_pCamera;
    void*        m_pReserved1;
    CSWCArea*    m_pArea;
    Vector       m_vSavedPlayerPos;
    Vector       m_vCameraPos;
    Vector       m_vCameraOffset;
    float        m_fReserved1;
    unsigned long long m_oidCameraFollow;
    float        m_fCameraDist;
    float        m_fCameraYaw;
    float        m_fCameraPitch;
    int          m_bCameraMoved;
    int          m_bCameraAutoTurning;
    int          m_bAutoTurnSuppressed;
    int          m_bFindClearView;
    char         m_nCameraSide;
    float        m_fPitchVelCache;
    float        m_fYawVel;
    float        m_fDistDecay;
    unsigned char m_nMinutesPerHour;
    int          m_nCalendarYear;
    int          m_nCalendarMonth;
    int          m_nCalendarDay;
    int          m_nCalendarHour;
    unsigned char m_nTimeOfDayState;
    float        m_fTimeOfDay;
    float        m_fHourLengthSec;
    unsigned char m_nDawnHour;
    unsigned char m_nDuskHour;
    char         m_aReserved1[0xf8-0xee];
    char         m_aReserved2[0x105-0xf8];
    unsigned char m_nLastCameraMode;
    char         m_aReserved3[2];
    int          m_bCameraModeChanged;
    int          m_nShakeTimeLeftMs;
    int          m_nShakeIntervalMs;
    int          m_nShakeDelayMs;
    int          m_nShakePeriodMs;
    int          m_bShakeReset;
    int          m_nBumpTimeLeftMs;
    int          m_nBumpParam;
    int          m_bBumpReset;
    int          m_bPlayerStationary;
    int          m_bCameraTurned;
    int          m_bCameraZoomed;
    int          m_nReserved1;
    int          m_nReserved2;
    CCameraSettings m_cSavedCameraSettings;
    CAurObject*  m_pAnimatedCameraModel;
    CExoString   m_sAnimatedCameraAnim;

    CSWCModule();
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 29 slots
    virtual ~CSWCModule();  // slots 0-1 (D2+D0)
    virtual CSWCModule* AsSWCModule();
    // </VTABLE-GEN>


    void UnloadModule();
    // Reads the module description off the wire and builds its area and camera. Nonzero on success.
    int  LoadModule();
    bool CanUpdate();
    CSWMiniGame* GetMiniGame();
    void UnloadAnimatedCamera();
    void BumpCamera(unsigned int nParam);
    void ShakeCamera(unsigned int nDelayMs, unsigned int nDurationMs);
    // Declared int rather than bool: callers OR the result into an int accumulator.
    int  IsCameraAnimated();
    void SetTimeOfDayState(unsigned char nState, unsigned int nMs);
    void SetCameraFollow(unsigned long long oid, int bFindClearView);
    float UpdateCameraCollision(float fParam1, float fParam2);
    int FindClearView(float fDeltaTime, float* pfYaw, float* pfPitch);
    void Update(float fDeltaTime);
    void ZoomCamera(float fDelta);
    bool SetFreeLookCamera(unsigned long long oid);
    void UpdateCameraBumpAndShake(float fDeltaTime);
    // fNearAdjust is unused; only fFarAdjust is applied, to both the camera's far clip and the
    // scene's far fog.
    void AdjustCameraClipRange(float fNearAdjust, float fFarAdjust);
    void ScrollCamera(Vector vDelta);
    void TiltCamera(float fParam);
    void AcclTiltCamera(float fParam);
    // The free-look arm rotates the player creature directly; AcclTurnCamera instead nudges
    // CSWCCreature::m_fFreeLookTurnVel.
    void TurnCamera(float fParam1, float fParam2);
    bool InterpolateDist(float fTargetDist, float fRate, float fDeltaTime);
    bool InterpolateYaw(float fTargetYaw, float fRate, float fDeltaTime);
    void UpdateCameraFollow(float fDeltaTime);
    void UpdateCameraModeChaseCam();
    void UpdateCameraModeEQ(float fDeltaTime);
    void UpdateCameraModeSW(float fDeltaTime);
    void UpdateCameraModeBG();
    void UpdateCameraModeNormal();   // same body as UpdateCameraModeBG
    bool ReAttachHAKFile();
    void AcclTurnCamera(float fParam1, float fParam2);

    // Places the camera behind the followed object: blends the smoothed target position toward the
    // object's world position, slerps a target orientation toward the camera's current one, and
    // puts the camera along the resulting forward vector at the smoothed distance.
    int  GetNextCameraPosition(float fDeltaTime, Vector* pvPos);

    float UpdatePushCameraCollision(float fParam1, float fParam2);
    float UpdateNormalCameraCollision(float fParam1, float fParam2);

    int RestoreCamera();

    CExoString GetModuleDisplayName() { return m_sModuleDisplayName; }

    void LoadAnimatedCamera(const CResRef& resRef);
    void SetDialogCamera(int nParam);
    bool SetCombatCamera();
    bool SetNavigateCamera();
    // Returns the started animation's length, 0 on any bail-out.
    float SetAnimatedCamera(unsigned short nAnimation, float fFOV, unsigned long long oid);
};
