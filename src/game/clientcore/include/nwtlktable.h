#pragma once
#include "k2stdint.h"

// Client-side talk table: CTlkTable's token lookup plus the per-lookup speaker state.

#include "exotlktable.h"

class CGameObject;

class CSWTlkTable : public CTlkTable {
public:
    // A token's m_nLanguage: stringtokens.2da's ActionCode column, what GetTokenValue substitutes.
    enum {
        TOKEN_ACTION_STRREF          = 0,    // the token's first strref
        TOKEN_ACTION_GENDER_STRREF   = 1,    // the strref for the speaker's gender
        TOKEN_ACTION_FULL_NAME       = 2,
        TOKEN_ACTION_FIRST_NAME      = 3,
        TOKEN_ACTION_LAST_NAME       = 4,
        TOKEN_ACTION_RACE            = 5,
        TOKEN_ACTION_RACE_LOWER      = 6,
        TOKEN_ACTION_SUBRACE         = 7,
        TOKEN_ACTION_CLASS           = 8,
        TOKEN_ACTION_CLASS_LOWER     = 9,
        TOKEN_ACTION_LEVEL           = 10,
        TOKEN_ACTION_ALIGNMENT       = 11,
        TOKEN_ACTION_ALIGNMENT_LOWER = 12,
        TOKEN_ACTION_LAW_CHAOS       = 13,
        TOKEN_ACTION_GOOD_EVIL       = 14,
        TOKEN_ACTION_GAME_YEAR       = 15,
        TOKEN_ACTION_GAME_TIME       = 16,
        TOKEN_ACTION_GAME_MONTH      = 17,
        TOKEN_ACTION_DAY_NIGHT       = 18,
        TOKEN_ACTION_START_ACTION    = 19,
        TOKEN_ACTION_START_CHECK     = 20,
        TOKEN_ACTION_START_HIGHLIGHT = 21,
        TOKEN_ACTION_END_HIGHLIGHT   = 22,   // "/Start"
        TOKEN_ACTION_PLAYER_NAME     = 23,
        TOKEN_ACTION_CHARACTER       = 24,   // the button glyph whose character code is the strref
        TOKEN_ACTION_KEY_NAME        = 25,   // the key bound to the input event in the strref
        TOKEN_ACTION_MOUSE_BUTTON    = 26,
        TOKEN_ACTION_BOUNTY_VALUE    = 27,   // KOTOR 2 only
    };

    // m_bSuppressEnabled's bit 0 lets the start tokens suppress the text that follows them.
    enum {
        SUPPRESS_ENABLED = 0x01,
    };

    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 1 slots
    virtual void GetTokenValue(CTlkTableToken const&, CExoString&);
    // </VTABLE-GEN>
    unsigned char GetObjectGender();

    CExoString Fetch(uint64_t strRef, CGameObject* pObject, int nMode, int bFlag);
    using CTlkTable::ParseStr;
    void ParseStr(CExoString& s, CGameObject* pObject, int nMode, int bFlag);

    CGameObject* m_pSpeakerObj;
    unsigned char m_bSuppressEnabled;
    char         _padf1[3];
    int          m_nPlayerId = 0;
};

extern CSWTlkTable* g_pSWTlkTable;

#include "appmanager.h"
#include "clientexoapp.h"

inline CExoString CSWTlkTable::Fetch(uint64_t strRef, CGameObject* pObject, int nMode, int bFlag)
{
    K2_UNUSED(nMode);
    m_pSpeakerObj = pObject;
    m_gender = GetObjectGender();
    m_bSuppressEnabled = static_cast<unsigned char>((m_bSuppressEnabled & ~SUPPRESS_ENABLED) | (bFlag & 1));
    return g_pAppManager->m_pClientExoApp->GetGUIString(strRef);
}

inline void CSWTlkTable::ParseStr(CExoString& s, CGameObject* pObject, int nMode, int bFlag)
{
    K2_UNUSED(nMode);
    m_pSpeakerObj = pObject;
    m_gender = GetObjectGender();
    m_bSuppressEnabled = static_cast<unsigned char>((m_bSuppressEnabled & ~SUPPRESS_ENABLED) | (bFlag & 1));
    CTlkTable::ParseStr(s);
}
