class CSWGuiSaveLoad : public CSWGuiPanel {
public:
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 30 slots
    virtual ~CSWGuiSaveLoad();  // slots 0-1 (D2+D0)
    virtual void Update(float f);
    virtual void HandleInputEvent(int type, int val);
    // </VTABLE-GEN>
    // b selects the save or load flavour: it seeds bit 0 of m_nModeFlags, swaps the two labels'
    // StrRefs and picks HandleSaveButton rather than VerifyLoadGame for BTN_SAVELOAD. c seeds bit
    // 1, the leave-the-module selector ExitPanel tests. d is stored into m_bEndGameMode.
#if KOTOR1
    // K1 takes three arguments and passes end-game mode 0.
    CSWGuiSaveLoad(CSWGuiManager* pGuiManager, int a, int b);
    CSWGuiSaveLoad(CSWGuiManager* pGuiManager, int a, int b, int)
        : CSWGuiSaveLoad(pGuiManager, a, b) {}
#else
    CSWGuiSaveLoad(CSWGuiManager* pGuiManager, int a, int b, int c);
#endif
    // Starts the cloud-save sync for the slot list; bParam selects the check-now path.
    void CheckCloudSync(bool bParam);

    // Stamps the dismissed state onto every panel in the chain, then either drops the modal or
    // leaves the module.
    void ExitPanel();
    // Repopulates the slot list and re-seats the selection.
    void ReloadGamesList(CSWGuiControl* pControl);
    // Advances the cloud state machine once the sync succeeds.
    void OnCloudSyncSuccess(CSWGuiControl* pControl);
    // Cycles the slot filter.
    void HandleFilterPress(CSWGuiControl* pControl);

    void SetEndGameMode();

    // The read side of CServerExoAppInternal::DoPCAutosave. bCloud selects the cloud slot name
    // rather than the autosave slot name.
#if KOTOR1
    void LoadPCAutoSave(const CExoString& sModule);
#else
    void LoadPCAutoSave(const CExoString& sModule, bool bCloud);
#endif

    // Empty stubs; neither is a vtable slot.
    void FinishSave(CSWGuiControl* pControl);
    void DisplayLoadError(uint64_t nStrRef);

    // Save-slot actions.
    bool UnpackGame(unsigned int nSlot, const CExoString& sModule,
                    CSWGuiControl* pControl);          // mirrors CGuiInGame::UnpackQuickSaveGame
    bool CopyGameToFutureGame(unsigned int a, const CExoString& b);  // mirrors
                                                    // CGuiInGame::CopyQuickSaveGameToFutureGame
    void WriteGame(const CExoString& sModule);
    void PromptForSaveName(CSWGuiControl* pControl);
    void RemoveGame(CSWGuiControl* pControl);
    void SaveNamePanelClose(int nResult, CExoString sName);
    void HandleCloudButton2(CSWGuiControl* pControl);
    // Confirms a cloud upload through the box DeleteGame uses, with its own prompt string and
    // HandleCloudButton2 as the callback.
    void HandleCloudButton(CSWGuiControl* pControl);
    // Probes the writable directory, then asks for overwrite confirmation, prompts for a name, or
    // reports that there is no room.
    void HandleSaveButton(CSWGuiControl* pControl);

    // Rebuilds the row widgets from the save directory listing and writes m_nNextSaveSlot.
    void PopulateGameList();
    // Fills m_saveList from the possibly filtered save list.
    void PopulateGameLB();

    // Confirm-box actions. Both ignore a press whose event argument is zero, then fill the shared
    // confirmation box and pop it through the manager.
    void DeleteGame(CSWGuiControl* pControl);
    // Two immediate-load conditions skip the prompt; otherwise the confirmation box runs LoadGame
    // as its callback.
    void VerifyLoadGame(CSWGuiControl* pControl);
    void CorruptGame(CSWGuiControl* pControl);
    // Selection sort, descending, on each entry's cached file time.
    void SortGamesByTimeStamp(CExoArrayList<CSWGuiControl*>& list);
    // Loads the selected save by one of three routes: the PC autosave, the leave-the-module path,
    // or an in-place load.
    void LoadGame(CSWGuiControl* pControl);
    // Loads the most recently used save, the first row of the list, once it matches the party
    // table's save name. Returns 1 only when LoadGame ran.
#if !KOTOR1
    int  LaunchMostRecentSave();
#endif
    // Selects the save row the given control names and holds the modal until it is dismissed.
    void ShowGame(CSWGuiControl* pControl);

#if KOTOR1
    IosFloatingButtonIcon m_iconCloud;
#else
    AspyrFloatingButtonIcon m_iconCloud;
#endif
    // m_nModeFlags: the save (rather than load) flavour, leaving the module after the panel (the
    // ExitPanel selector), and the filter tabs already built from the save list.
    enum {
        SAVELOAD_MODE_SAVE = 0x01,
        SAVELOAD_MODE_EXIT_MODULE = 0x02,
        SAVELOAD_MODE_FILTERS_BUILT = 0x04,
    };
    unsigned char m_nModeFlags;
    char _pad311[0x314 - 0x311];
    unsigned int m_nNextSaveSlot;
    CExoString m_sResourceDir;
    CSWGuiLabel m_lblPanelName;
    CSWGuiLabel m_lblScreenshot;
    CSWGuiLabel m_lblPlanetName;
    CSWGuiLabel m_lblAreaName;
    CSWGuiLabel m_aPMLabels[3];
    CSWGuiListBox m_saveList;
#if !KOTOR1
    CSWGuiLabel m_lblPCName;
    CSWGuiLabel m_lblTimePlayed;
#endif
    CSWGuiButton m_btnSaveLoad;
    CSWGuiButton m_btnBack;
    CSWGuiButton m_btnDelete;
#if !KOTOR1  // K1 has no filter button, PC-name / time-played labels, entry list or cloud state
    CSWGuiButton m_btnFilter;
    CSWGuiLabel m_aBarLabels[4];
    CExoArrayList<CSWGuiSaveLoadEntry*> m_entries;
    int  m_nFilterIndex;
    char _pad277c[0x2780 - 0x277c];
    CExoArrayList<CExoString> m_filterNames;
    int  m_nReserved1;
    int  m_bEndGameMode;
    // m_nCloudSyncState: the save list's cloud sync, started with no saves on disk (the Cloud0000
    // placeholder) and finished by OnCloudSyncSuccess.
    enum {
        CLOUD_SYNC_NONE = 0,
        CLOUD_SYNC_STARTED = 1,             // the sync is in flight; rows are not collected
        CLOUD_SYNC_PENDING = 2,             // the list was rebuilt; waiting for OnCloudSyncSuccess
        CLOUD_SYNC_FINISHED = 3,
    };
    int  m_nCloudSyncState;
    char _pad279c[0x27a0 - 0x279c];
#endif
    CSWGuiButton m_btnCloud;
};

