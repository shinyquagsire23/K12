#else  // K1
K2_LAYOUT_ASSERT(sizeof(CSWGuiSaveLoadEntry) == 0x310, "CSWGuiSaveLoadEntry K1 size drift");
K2_LAYOUT_ASSERT(__builtin_offsetof(CSWGuiSaveLoadEntry, _pad26a) == 0x249, "K1's flag run is one byte");
