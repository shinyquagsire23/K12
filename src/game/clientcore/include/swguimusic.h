    CSWGuiListBox m_listBox;

    // The playable table, in 2DA order, and the playback state.
    CExoArrayList<CMusicItemInfo> m_aSongs;
    CExoStreamingSoundSource* m_pMusic;
    // Seeded with 8, the engine-wide music priority.
    int           m_nPriority;
    CExoString    m_sReserved1;
    CSWGuiControl* m_pSelectedRow;     // the listbox row currently tinted
    int           m_nLooping;
    int           m_nPlaying;
    float         m_fTimer;            // seconds left of the next-track grace delay
    int           m_nNumSongs;         // cached row count for the track counter
    int           m_nMusicVolume;      // cached option value, saved back on teardown
