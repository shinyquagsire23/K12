    CSWGuiTitleMusic(CSWGuiManager* pGuiManager);

    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 30 slots
    virtual ~CSWGuiTitleMusic();
    virtual void Draw(float f);
    virtual void HandleInputEvent(int type, int val);
    // </VTABLE-GEN>

    void PopulateSongList();
    void StopMusic();

    void OnPlayPicked(CSWGuiControl* pControl);    // BTN_PLAY
    void OnLoopPicked(CSWGuiControl* pControl);    // BTN_LOOP
    void OnStopPicked(CSWGuiControl* pControl);    // BTN_STOP
    void OnNextPicked(CSWGuiControl* pControl);    // BTN_NEXT, and the auto-advance
    void OnSongPicked(CSWGuiControl* pControl);    // a listbox row

    void OnEnterSlider(CSWGuiControl* pControl);        // hover in, the thumb pulses
    void OnExitSlider(CSWGuiControl* pControl);         // hover out
    void OnMoveVolumeSlider(CSWGuiControl* pControl);   // applies the music volume live

    CSWGuiLabel   m_labelMusicTitle;
    CSWGuiLabel m_aBars[3];
