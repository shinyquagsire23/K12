// The on-disk GFF header (56 bytes). m_pHeader points at one, either the raw resource-cache buffer
// or a grown one on the write path. Every multi-byte field is read through ByteSwap.
struct GFFHeader {
    char         sFileType[4];
    char         sFileVersion[4];
    unsigned int nStructOffset;
    unsigned int nStructCount;
    unsigned int nFieldOffset;
    unsigned int nFieldCount;
    unsigned int nLabelOffset;
    unsigned int nLabelCount;
    unsigned int nFieldDataOffset;
    unsigned int nFieldDataCount;
    unsigned int nFieldIndicesOffset;
    unsigned int nFieldIndicesCount;
    unsigned int nListIndicesOffset;
    unsigned int nListIndicesCount;
};

// On-disk struct record (12 bytes). A single field's index is stored in nDataOrDataOffset itself;
// several make it an offset into the field-indices array.
struct CResGFFStruct {
    unsigned int nType;
    unsigned int nDataOrDataOffset;
    unsigned int nFieldCount;
};

// On-disk field record (12 bytes). Fixed types that fit in four bytes store the value in the record;
// everything else stores an offset, chosen by nType.
struct CResGFFField {
    unsigned int nType;
    unsigned int nLabelIndex;
    unsigned int nDataOrDataOffset;
};

// An on-disk label, a fixed 16-byte string, not necessarily terminated.
struct GFFLabel {
    char s[16];
};

// An on-disk localized-string header (12 bytes) carries the byte count of everything after it, the
// TLK string ref (all-ones when there is none), then that many substrings.
struct ExoLocStringHeader {
    unsigned int nTotalSize;
    unsigned int nStringRef;
    unsigned int nStringCount;
};

// One localized substring, an 8-byte header then raw, unterminated UTF-8. The language id packs
// language*2 + gender.
struct ExoLocSubString {
    unsigned int nLanguageID;
    unsigned int nStringLength;
};

