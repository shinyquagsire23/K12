#pragma once

#include "Vector.h"
#include "exoresman.h"

class CGameObject;
struct Vector;
template<class T> class CExoArrayList;

// Shared base of the two area classes, CSWSArea (server) and CSWCArea (client).
class CSWArea {
public:
    CSWArea();
    // Builds the static-object registry. The derived constructors call it once their other bases are
    // in place, so it stays out of this constructor.
    void InitializeStaticObjects();

    // Static-object registry. Each entry names a slice of the shared vertex pool and of the shared
    // flat triangle-index pool.
    int  AddStaticObject(unsigned long long objectId, const Vector& vMin, const Vector& vMax,
                         int nVertexCount, Vector* pVertices, int nTriangleCount,
                         int* pTriangles);
    void GrowStaticObjectArray();
    void GrowStaticObjectVertices(int nAdditional);
    void GrowStaticObjectTriangles(int nAdditional);
    void RemoveStaticObject(int nIndex);

    // Walkmesh and clipping tolerances, defined out of line so readers load the shared value.
    static const float MAX_TILE_EPSILON;
    static const float MIN_TILE_EPSILON;
    static const float EPSILON;
    static const float SPLINE_COSINE_LIMIT;

    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 6 slots
    virtual ~CSWArea();  // slots 0-1 (D2+D0)
    virtual int GetIsIDInExcludeList(unsigned long long, CExoArrayList<CGameObject*>*);
    virtual int SetFog(float fogNear, float fogFar, Vector color);
    virtual int SetIsNight(int bIsNight);
    virtual int SetWind(unsigned char wind);
    // </VTABLE-GEN>
    // Segment-pair intersection in the area's X/Y plane. The out-params receive the crossing point's
    // coordinates, not parameters along either segment; returns 0 for collinear, parallel or
    // non-overlapping segments.
    int IntersectLineSegments(float ax, float ay, float bx, float by,
                              float cx, float cy, float dx, float dy,
                              float* pOutT1, float* pOutT2);

    int GetIsNight();

    int  RemoveStaticBoundingBox(unsigned long long objectId);
    int  AddStaticBoundingBox(unsigned long long objectId, const Vector& vMin,
                              const Vector& vMax);

    unsigned int m_nAreaFlags;
    int    m_nWidth;
    int    m_nHeight;
    int    m_nStaticObjectCapacity;
    int    m_nStaticObjectCount;
    unsigned long long* m_pStaticObjectIds;
    int*   m_pStaticObjectFirstTriangles;
    int*   m_pStaticObjectTriangleCounts;
    int*   m_pStaticObjectFirstVertices;
    int*   m_pStaticObjectVertexCounts;
    int    m_nStaticTriangleIndexCapacity;
    int    m_nStaticTriangleCount;
    int*   m_pStaticTriangleIndices;
    int    m_nStaticVertexCapacity;
    int    m_nStaticVertexCount;
    Vector* m_pStaticVertices;
    int    m_nStaticBBoxCapacity;
    int    m_nStaticBBoxCount;
    Vector* m_pStaticBBoxes;
    unsigned long long* m_pStaticBBoxIds;

    Vector m_fogColor;
    float  m_fogNear;
    float  m_fogFar;
    unsigned int  m_moonAmbientColor;
    unsigned int  m_moonDiffuseColor;
    unsigned int  m_moonFogColor;
    float         m_moonFogNear;
    float         m_moonFogFar;
    unsigned char m_moonFogOn;
    unsigned char _pada9[0xac-0xa9];
    int           m_moonShadows;
    unsigned int  m_sunAmbientColor;
    unsigned int  m_sunDiffuseColor;
    unsigned int  m_nFogColor;
    float         m_sunFogNear;
    float         m_sunFogFar;
    unsigned char m_sunFogOn;
    int           m_sunShadows;
    int           m_dayNightCycle;
    int           m_isNight;
    unsigned char m_chanceRain;
    unsigned char m_chanceSnow;
    unsigned char m_chanceLightning;
    unsigned char m_windPower;
    unsigned int  m_dynAmbientColor;
    int           m_noRest;
    unsigned char m_shadowOpacity;
    unsigned char _pade1[0xe4-0xe1];
    int           m_cameraStyle;
    CResRef       m_defaultEnvMap;
    unsigned int  m_grassAmbient;
    unsigned int  m_grassDiffuse;
#if !KOTOR1  // K1 has no grass emissive colour; everything after it sits 4 bytes lower
    unsigned int  m_grassEmissive;
#endif
    float         m_grassDensity;
    float         m_grassQuadSize;
    float         m_grassProbLL;
    float         m_grassProbLR;
    float         m_grassProbUL;
    float         m_grassProbUR;
    CResRef       m_grassTexName;
    float         m_alphaTest;
};

K2_LAYOUT_ASSERT(sizeof(CSWArea) == 0x130, "CSWArea must be 0x130 (CSWCArea/CSWSArea base split)");
#if KOTOR1  // K1 has no grass emissive colour, so every offset past it is 4 lower
K2_LAYOUT_ASSERT(__builtin_offsetof(CSWArea, m_grassDensity) == 0x100, "K1 CSWArea layout");
K2_LAYOUT_ASSERT(__builtin_offsetof(CSWArea, m_grassProbUR) == 0x114, "K1 CSWArea layout");
K2_LAYOUT_ASSERT(__builtin_offsetof(CSWArea, m_grassTexName) == 0x118, "K1 CSWArea layout");
K2_LAYOUT_ASSERT(__builtin_offsetof(CSWArea, m_alphaTest) == 0x128, "K1 CSWArea layout");
#endif
