#pragma once
#include "k2stdint.h"

// The localized-string table reader (dialog.tlk).

#include "exostring.h"
#include "CExoArrayListDtors.h"
#include "exofile.h"

struct STR_RES;

class CExoString;

// One opened .tlk file, an aliased CExoFile plus the 20-byte on-disk header it reads just past the
// base.
class CTlkFile : public CExoFile {
public:
    CTlkFile(const CExoString& resRef);
    int ReadHeader();

    // The accepted header version.
    static const char* TLK_FILE_VERSION;

    unsigned int m_nFileType;
    unsigned int m_nVersion;
    unsigned int m_nLanguageID;
    unsigned int m_nStringCount;
    unsigned int m_nStringTableOffset;
};
// The substitution record handed to GetTokenValue, built by the dialogue GUI from the current
// node.
class CTlkTableToken {
public:
    unsigned int  m_nNameHash;
    CExoString    m_sName;
    int           m_nLanguage;
    unsigned int  m_StrRefs[4];
    int           m_nStringRef;
};

// One entry of the custom-token table, the <CUSTOM0>-style substitutions a module sets at runtime.
class CTlkTableCustomToken {
public:
    int        m_nId;
    CExoString m_sValue;
};

class CTlkTable {
public:
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 1 slots
    virtual void GetTokenValue(CTlkTableToken const&, CExoString&);
    // </VTABLE-GEN>
    // The gender selector Fetch's third parameter takes.
    static const unsigned char GENDER_MALE;
    static const unsigned char GENDER_FEMALE;
    static const unsigned char NUM_CONTENT_PKGS;
    // The highest token id the engine reserves for itself. A custom token is only broadcast to
    // clients when its id is strictly greater.
    static const int CUSTOMTOKEN_RESERVED_END;

    // Two pairs of override tables, filled from the <tlk>_touch and <tlk>_control localized-string
    // files: set 0 for the touch and gamepad-selected strings, set 1 for the other.
#if !KOTOR1  // K1 has no override tables and the files start earlier
    CExoArrayList<int>   m_overrideStrRefs[2];
    CExoArrayList<char*> m_overrideStrings[2];
#endif

    // The opened .tlk files by [index][gender], where [i][0] is the male and base file and [i][1]
    // the "F"-suffixed one AddFile opens alongside it. The two may alias, since AddFile copies
    // [i][0] into [i][1] when the second file cannot be opened.
    CTlkFile*            m_pTlkFiles[7][2];

    unsigned char  m_gender;
    char _padB9[0xc0 - 0xb9];

    CTlkTableToken* m_pStringTokens;
    unsigned int    m_nStringTokenCount;
    char _padCC[0xd0 - 0xcc];

    CTlkTableCustomToken* m_pCustomTokens;
    unsigned int m_nCustomTokenCount;
    int  m_bSuppressText;
    int  m_bShowStringRefs;
    char _pade4[0xe8 - 0xe4];

    CTlkTable();
    ~CTlkTable();

    int  ExoIsDBCSLeadByte(unsigned char c);
    char* RemapFontName(char* pName);
    // Walks the opened files for the current gender, falling back to the male file when the
    // gendered one has no entry. bParse opts into ParseStr.
    int  FetchInternal(unsigned int strRef, STR_RES& out, int bParse);
    int  RemoveFile(int nIndex);

    int OpenFile(const CExoString& path);
    int GetLanguageVersion();
    // Registers a downloaded-content TLK file into the fixed files array. A no-op on an empty path
    // or an out-of-range index.
    int  AddFile(const CExoString& sPath, int nIndex);
    void ClearCustomTokens();
    void SetCustomToken(int nId, const CExoString& sValue);
    CExoString GetSimpleString(uint64_t strRef);
    int  Fetch(unsigned int strRef, STR_RES& out, unsigned char gender);
    void ParseStr(CExoString& s);
};
