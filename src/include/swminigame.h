#pragma once

// One vehicle's per-frame physics pair. CSWMiniGame embeds two of them by value, and
// CSWMiniPlayer::Control differences the two states field by field into its offset accumulator.

#include "Vector.h"
#include "Vector.h"
#include "Quaternion.h"

struct CSWMGPhysicsState {
    Vector m_vVelocity;
    Vector m_vPosition;
};

#include "CResHelper.h"
#include "CExoArrayListDtors.h"
#include "SafePointer.h"
#include "exoresman.h"

class CAurBehavior;
class CAurCamera;
class CAurObject;
class CSWCArea;
class CSWCRoom;
class C2DA;
class CSWMGBehaviorBullet;
class CSWMGObstacle;
class CSWMiniEnemy;
class CSWMiniPlayer;
class CSWTrackFollower;
class CExoStreamingSoundSource;
#include "resare.h"
struct SWMGExplodeBullet;

// One prototype-track entry, the element of m_protoTracks.
struct SWMGTrackInfo {
    CResRef m_resTrack;
    Vector  m_vPosition;
};

// One live explode bullet, holding the render object the spark is attached to, the point it went
// off at and the orientation it faces along.
struct SWMGExplodeBullet {
    SafePointer<CAurObject> m_spObject;
    Vector     m_vHitPosition;
    Quaternion m_qOrientation;
};

class CSWMiniGameObject;

// Swoop-race and turret minigame controller, client side.
class CSWMiniGame : public CResHelper<CResARE, 2012> {
public:
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 2 slots
    virtual ~CSWMiniGame();  // slots 0-1 (D2+D0)
    // </VTABLE-GEN>
    // m_type (the ARE's MiniGame Type field): a swoop race or a turret run.
    enum MiniGameType {
        MINIGAME_TYPE_SWOOP  = 1,
        MINIGAME_TYPE_TURRET = 2,
    };
    // The world axis a mouse axis (Mouse_AxisX/Y, negated to flip it) or the Bump_Plane field
    // names.
    enum MiniGameAxis {
        MINIGAME_AXIS_X = 1,
        MINIGAME_AXIS_Y = 2,
        MINIGAME_AXIS_Z = 3,
    };
    CExoStreamingSoundSource* m_pSound;
    CAurCamera* m_pCamera;
    CSWTrackFollower* m_pPlayer;
    CSWCArea* m_pArea;
    CExoArrayList<unsigned int>     m_enemyIds;
    CExoArrayList<SWMGTrackInfo*> m_protoTracks;
    CExoArrayList<unsigned int>     m_obstacleIds;
    CExoArrayList<SafePointer<CAurObject>*> m_bullets;
    CExoArrayList<SWMGExplodeBullet*> m_explodeBullets;
    float  m_clipNear;
    float  m_clipFar;
    float  m_viewAngle;
    float  m_movementPerSecond;
    int    m_bumpPlane;
    int    m_dof;
    int    m_type;
    int    m_mouseAxisX;
    int    m_mouseAxisY;
    float  m_fBankAngle;
    int    m_bBankDetentLatched;
    unsigned char m_bUseInertia;
    unsigned char m_bDoBumping;
    CResRef m_resForfeitSound;
    CSWCRoom* m_pPlayerRoom;
    int    m_nPhysicsModel;
    Vector m_vSteerAxis;
    float  m_lateralAccelPerSec;
    CSWMGPhysicsState m_prevPhysicsState;
    CSWMGPhysicsState m_curPhysicsState;
#if !KOTOR1  // K1 ends after the physics pair
    float  m_fReserved1;
    float  m_fReserved2;
    float  m_fReserved3;
    C2DA*  m_pSwoopUpgrades;
    int    m_swoopUpgrades[6];
    float  m_jumpSpeed;
#endif

    CSWMiniGame(CSWCArea* pArea);
    void  SetCurPos(Vector v);
    void  SetMovementPerSecond(float mps);
    int   SetMouseAxisX(int axis);
    int   SetMouseAxisY(int axis);
    int   SetBumpPlane(int plane);
    int   SetDOF(int dof);
    int   SetType(int type);
    int   SetPlane(int& plane, int value);
    int   GetAttachType();
    int   HitCheckBullet(CAurObject* pBullet, CAurObject* pTarget,
                         CSWMiniGameObject* pOwner);
    void  GetClipDist(float* pNear, float* pFar);
    void  SetClipDist(float fNear, float fFar);
    void  SetViewAngle(float fAngle);
    SWMGTrackInfo* GetProtoTrack(int index);
    // The "Music" field lands in m_resForfeitSound.
    void SetMusic(const CResRef& resMusic) { m_resForfeitSound = resMusic; }
    void SetCurrentPhysicsState(CSWMGPhysicsState sState) { m_curPhysicsState = sState; }
    void SetPreviousPhysicsState(CSWMGPhysicsState sState) { m_prevPhysicsState = sState; }
    SWMGTrackInfo* GetProtoTrack(const CResRef& resTrack);
    SWMGTrackInfo* AddTrack(const CResRef& resTrack, const Vector& vPosition);
    Vector BumpPlane(const Quaternion& qRot);
    // Each clears one of the three lists and returns the number of entries it held.
    int   ClearTracks();
    int   ClearEnemies();
    int   ClearObstacles();
    void  Stop();
    void  Resume();
    void  SetupSwoopUpgrades();
    CSWMiniEnemy* GetEnemy(int index);
    CSWMGObstacle* GetObstacle(int index);
    CSWMGObstacle* RemoveObstacle(CSWMGObstacle* pObstacle);
    CSWMGObstacle* AddObstacle(const CResRef& resName, const Vector& vPosition);
    CSWMiniEnemy* AddEnemy(CSWMiniEnemy* pEnemy);
    // Builds a fresh enemy, loads its model resrefs (flags is parallel, one attach flag byte per
    // model), then builds the track object named by resTrack, places it at the prototype entry
    // carrying the same resref when one exists and attaches the enemy to it.
    CSWMiniEnemy* AddEnemy(CExoArrayList<CResRef>& resModels,
                           CExoArrayList<unsigned char>& flags,
                           const CResRef& resTrack);
    int   Load();
    // Attaches the camera to the player's vehicle: type 1 uses the first player model carrying a
    // camerahook part, falling back to the track's own, and type 2 hands the player's spare model to
    // the camera. Then re-pushes the clip and view state.
    CAurCamera* SetCamera(CAurCamera* pCamera);
    void  Go();
    void  Update(float deltaTime);
    void  DoHitCheck();
    void  AddBullet(CAurObject* pBullet);
    void  RemoveBullet(CAurObject* pBullet);
    // Drops every spawned bullet's owner back-pointer to a track follower that is going away, so a
    // still-flying bullet cannot reach a freed vehicle.
    void  UpdateBulletParent(CSWTrackFollower* pFollower);
    CSWMiniPlayer* SetPlayer(CSWMiniPlayer* pPlayer);
    // Tears the old vehicle down, builds a fresh player and its model list, then builds and places
    // the track named by the third resref.
    CSWMiniPlayer* SetPlayer(CExoArrayList<CResRef>& resModels,
                             CExoArrayList<unsigned char>& flags,
                             const CResRef& resTrack);
    // The same build plus one extra model from resCameraHook, handed to
    // CSWMiniPlayer::SetCameraHook with bCameraHook as its flag.
    CSWMiniPlayer* SetPlayer(CExoArrayList<CResRef>& resModels,
                             CExoArrayList<unsigned char>& flags,
                             const CResRef& resTrack,
                             const CResRef& resCameraHook,
                             unsigned char bCameraHook);
    CSWMiniEnemy* RemoveEnemy(CSWMiniEnemy* pEnemy);
    // Runs the swoop and turret per-frame tick: hands the vehicle's two physics states to
    // CSWMiniPlayer::Control, copies the refreshed current state over the previous one, then turns
    // the steering value into a bank animation.
    void  Control(float fDelta);
    // One fourth-order Runge-Kutta step of the vehicle's velocity and position, with the acceleration
    // along the axis and a lateral drag term proportional to the velocity. Type 1 also applies
    // gravity to the z velocity plus two lateral velocity clamps.
    void  AxisAcceleration(const Vector& vAxis, float fDelta);
    // Moves the vehicle with the stick directly: the position is last frame's plus the axis scaled
    // by the speed and the frame time.
    void  AxisVelocity(const Vector& vAxis, float fDelta)
    {
        m_curPhysicsState.m_vPosition = m_prevPhysicsState.m_vPosition + m_movementPerSecond * vAxis * fDelta;
    }
    void  UpdateAxis(Vector& vAxis, float fDelta);
    void  UpdateJoystick(float fX, float fY, float fDelta);
    void  UpdateMouse(float fX, float fY, float fDelta);
};
