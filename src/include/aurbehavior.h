#pragma once

// The Aurora camera and object behavior base. CAurCamera::GetBehavior hands these out.
//
// AddDependency and RemoveDependency are exported member functions but not virtual.

#include "List.h"
#include "SafePointer.h"

class CAurBehaviorCameraFollow;
class CAurObject;

// The camera behaviours' GetType ids, one per behaviour class, and CAurCamera::GetBehavior's
// "the current one".
enum {
    BEHAVIOR_CURRENT               = -1,
    BEHAVIOR_CAMERA_ON_A_STICK     = 0x106a,
    BEHAVIOR_CAMERA_STATIC_TRACKER = 0x106b,
    BEHAVIOR_CAMERA_FOLLOW         = 0x106c,
    BEHAVIOR_CAMERA_DIALOG         = 0x106d,
    BEHAVIOR_CAMERA_FREE_LOOK      = 0x106e,
    BEHAVIOR_CAMERA_DEATH          = 0x106f,
    BEHAVIOR_CAMERA_COMBAT         = 0x1070,
    BEHAVIOR_CAMERA_NAVIGATE       = 0x1071,
};

// Derived classes place their own fields from this base's real sizeof, so getting it right matters.
class CAurBehavior {
public:
    // <VTABLE-GEN: binary ground truth (_ZTV) — regenerated by tools/hoist_headers.py; do not edit inside markers */
    //   primary vtable, 9 slots
    virtual ~CAurBehavior();  // slots 0-1 (D2+D0)
    virtual void SetScene();
    virtual int Control(float fParam);
    virtual void Message(char* pszParam);
    virtual int GetType();
    virtual void* AsBehaviorAttach();
    virtual void* AsBehaviorNavigate();
    virtual CAurBehaviorCameraFollow* AsBehaviorCameraFollow();
    // </VTABLE-GEN>

    // The objects this behavior depends on, as a List of SafePointer<CAurObject>* nodes.
    List<SafePointer<CAurObject>*> m_dependencies;
    CAurObject* m_pOwner;

    CAurBehavior(CAurObject* pOwner);

    // Not virtual: the constructor calls AddDependency directly to attach the behavior to its owner.
    void AddDependency(CAurObject* pObject);
    void RemoveDependency(CAurObject* pObject);
};
