#!/usr/bin/env python3
"""embedfiles.py -- compile files from resources/ into the binary.

    embedfiles.py --out k2embedded.gen.cpp DIR [DIR...]

Every file directly in each DIR is embedded under its file name (a later DIR's file of the same
name replaces an earlier one), and the generated C++ answers

    extern "C" const unsigned char* k2embedded_find(const char* pszName, size_t* pnSize);

with the bytes (NUL-terminated past *pnSize) of the file named pszName, compared case-blind, or
NULL. The callers use it as the last resort after the working directory and the OBBs: the GLSL
shaders the port's renderer reads by name (kotor.vert ...), which the PC data sets (the Steam
installs) do not have. The output is rewritten only when it changes, so a configure run does not
recompile it.
"""
import argparse
import os
import sys


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    ap.add_argument('dirs', nargs='+')
    args = ap.parse_args()

    files = {}
    for d in args.dirs:
        for name in sorted(os.listdir(d)):
            path = os.path.join(d, name)
            if os.path.isfile(path) and not name.startswith('.'):
                files[name.lower()] = (name, path)

    out = ['// Generated by platforms/tools/embedfiles.py from ' +
           ', '.join(os.path.relpath(d, os.path.dirname(os.path.abspath(args.out))) for d in args.dirs) +
           ' -- do not edit.',
           '#include <stddef.h>', '#include <strings.h>', '', 'namespace {']
    rows = []
    for i, key in enumerate(sorted(files)):
        name, path = files[key]
        data = open(path, 'rb').read()
        out.append(f'// {name}')
        out.append(f'const unsigned char k{i}[] = {{')
        for o in range(0, len(data), 24):
            out.append('    ' + ''.join(f'{b},' for b in data[o:o + 24]))
        out.append('    0};')
        rows.append(f'    {{"{name}", k{i}, {len(data)}}},')
    out += ['struct Embedded {', '    const char* pszName;', '    const unsigned char* pData;',
            '    size_t nSize;', '};', 'const Embedded kFiles[] = {'] + rows + ['};', '} // namespace', '',
            'extern "C" const unsigned char* k2embedded_find(const char* pszName, size_t* pnSize)',
            '{',
            '    for (const Embedded& e : kFiles)',
            '        if (strcasecmp(pszName, e.pszName) == 0) {',
            '            *pnSize = e.nSize;',
            '            return e.pData;',
            '        }',
            '    return 0;',
            '}', '']
    text = '\n'.join(out)
    if os.path.exists(args.out) and open(args.out, encoding='utf-8').read() == text:
        return 0
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, 'w', encoding='utf-8') as f:
        f.write(text)
    print(f'embedfiles: {len(files)} file(s) -> {args.out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
