// usage: UNBIKIT_SRC=/path/to/unbikit/src node --experimental-strip-types gentables.mjs <outdir>
const C = await import(process.env.UNBIKIT_SRC + '/bik-constants.ts');
const u = C.unpackValues;
const t = {
  bink_patterns: [u(2, C.PACKED_BIK_PATTERNS), 'uint8_t'],
  bink_scan: [u(2, C.PACKED_BIK_SCAN), 'uint8_t'],
  bink_tree_codes: [u(2, C.PACKED_BIK_TREE_CODES), 'uint8_t'],
  bink_tree_lens: [u(1, C.PACKED_BIK_TREE_LENS), 'uint8_t'],
  bink_audio_band_freqs: [u(3, C.PACKED_AUDIO_CRITICAL_FREQS), 'uint16_t'],
  bink_audio_rle_lengths: [u(2, C.PACKED_AUDIO_RLE_LENGTH_TABLE), 'uint16_t'],
};
let out = `/*
 * k2bink -- format tables: block patterns, DCT scan order, the 16 predefined Huffman code sets,
 * audio band edges and RLE run lengths. (The DCT quantizers come from tools/extract_quant.py.)
 *
 * GENERATED by platforms/video/tools/gentables.mjs from unbikit's packed constants
 * (https://github.com/blennies/unbikit, src/bik-constants.ts). Do not edit.
 * Copyright 2025 David Hart. SPDX-License-Identifier: MIT OR Apache-2.0
 */
#include "k2bink_tables.h"
`;
let hdr = `/* GENERATED by platforms/video/tools/gentables.mjs. SPDX-License-Identifier: MIT OR Apache-2.0 */
#ifndef K2BINK_TABLES_H
#define K2BINK_TABLES_H
#include <stdint.h>
`;
for (const [name, [vals, type]] of Object.entries(t)) {
  if (vals.some(v => !Number.isInteger(v))) throw new Error(name);
  hdr += `extern const ${type} ${name}[${vals.length}];\n`;
  out += `\nconst ${type} ${name}[${vals.length}] = {\n`;
  for (let i = 0; i < vals.length; i += 16) out += '    ' + vals.slice(i, i + 16).join(', ') + ',\n';
  out += '};\n';
}
hdr += 'extern const int32_t bink_quant[2048];   /* k2bink_quant.c: intra then inter, natural order */\n#endif\n';
const fs = await import('node:fs');
fs.writeFileSync(process.argv[2] + '/k2bink_tables.c', out);
fs.writeFileSync(process.argv[2] + '/k2bink_tables.h', hdr);
