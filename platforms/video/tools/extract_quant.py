#!/usr/bin/env python3
"""Extract Bink 1's DCT quantizer tables from the original game binary -> k2bink/k2bink_quant.c.

The Bink SDK statically linked into libkotor2.so (arm64) keeps two static tables of 16 levels x 64
int32 (16.16-ish fixed point, consumed as `coef * q >> 11`), in natural row-major 8x8 order:
  inter @ 0xa08b80, intra @ 0xa09b80
read by the fused dequant+IDCT routines FUN_00936cf8 (put/add) and FUN_0093705c (2x-scaled put).
unbikit derives these by scaling one base matrix with float factors; that is off by up to 22 at the
high levels, which is visible as sparse +-1 pixel errors.

  python3 platforms/video/tools/extract_quant.py [path/to/arm64/libkotor2.so]
"""
import hashlib, os, struct, sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
SO = sys.argv[1] if len(sys.argv) > 1 else os.path.join(
    REPO, 'decomp_bins/swkotorii_extracted/lib/arm64-v8a/libkotor2.so')
TABLES = (('intra', 0xa09b80), ('inter', 0xa08b80))   # file offset == vaddr in the first PT_LOAD

data = open(SO, 'rb').read()
vals = []
for _, off in TABLES:
    vals += struct.unpack_from('<1024i', data, off)
# sanity: level 0 of intra starts 1.0 (65536) and every level scales monotonically
assert vals[0] == 65536 and vals[1024] == 65536, 'tables not found at the expected offsets'

out = ['/*',
       ' * k2bink -- Bink 1 DCT quantizer tables: [0..1023] intra, [1024..2047] inter; 16 levels x 64',
       ' * entries each, NATURAL (row-major 8x8) order. Applied as (coef * q) >> 11.',
       ' *',
       ' * GENERATED by platforms/video/tools/extract_quant.py from the Bink SDK statically linked into',
       ' * libkotor2.so (arm64, sha1 %s): intra @0xa09b80, inter @0xa08b80.' % hashlib.sha1(data).hexdigest()[:12],
       ' * Do not edit.',
       ' */',
       '#include "k2bink_tables.h"',
       '',
       'const int32_t bink_quant[2048] = {']
for i in range(0, 2048, 8):
    out.append('    ' + ', '.join(str(v) for v in vals[i:i + 8]) + ',')
out += ['};', '']
dst = os.path.join(os.path.dirname(__file__), '..', 'k2bink', 'k2bink_quant.c')
open(dst, 'w').write('\n'.join(out))
print('wrote', os.path.normpath(dst))
